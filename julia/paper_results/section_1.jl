# Section 1 of the paper: run by paper_results.jl, which defines the helpers used here.

"The [complex] table of the stored 08_summary.toml of a census target."
s1_stored_complex(target) = TOML.parsefile(joinpath(TARGET_DIRECTORIES[target], "08_summary.toml"))["complex"]

function section_1()
    subheading("The group G2 as the stabilizer of Φ = e123 + e456 + e147 + e257 + e367")
    check("dim G2 = dim Lie(Stab_SL7(Φ)) over QQ", 14, first(stabilizer_dimension(QQ; trace_zero=true)))
    cited("G2 is the automorphism group of the octonions [Springer–Veldkamp, §2.3]")
    cited("over every field K, the stabilizer of Φ in SL7 is the split simple group of type G2 [Aschbacher, (2.11) and (3.4)]")
    d, A = stabilizer_dimension(QQ)
    kernel = nullspace(A)[2]
    algebra = [[kernel[7 * (i - 1) + m, b] for m in 1:7, i in 1:7] for b in 1:ncols(kernel)]
    claim("G2 ⊂ SO(7, q): every element X of Lie(G2) satisfies XᵀB + BX = 0 for the polar form B of q",
          all(X -> all(iszero, transpose(X) * POLAR + POLAR * X), algebra), "$(length(algebra)) basis elements")
    # POLAR is the Gram matrix of 2q; the paper's signature (3,4) is (positive, negative)
    check("signature of q over RR (positive, zero, negative)", (3, 0, 4),
          signature_tuple(quadratic_space(QQ, matrix(QQ, POLAR))))
    claim("q is split: span(e1, e2, e3) is totally isotropic, of the maximal dimension 3", all(iszero, POLAR[1:3, 1:3]))

    subheading("The quadric q from the Pfaffians of Φ(x, ., .), eq:Phi2")
    R, x = polynomial_ring(QQ, ["x$i" for i in 1:7])
    q = x[1] * x[4] + x[2] * x[5] + x[3] * x[6] - x[7]^2
    A2 = [sum(phi(i, j, k) * x[i] for i in 1:7) for j in 1:7, k in 1:7]
    info("Φ(x, ., .) = " * join(["x$i·(" * join(["$(phi(i, j, k) > 0 ? "+" : "-")e$j$k" for (j, k) in PAIRS if phi(i, j, k) != 0], " ") * ")" for i in 1:7], " "))
    as_vector(t) = [QQ(get(Dict(t), PAIRS[k], 0)) for k in 1:21]
    paper_Phi2 = [[(2, 3) => 1, (4, 7) => 1], [(1, 3) => -1, (5, 7) => 1], [(1, 2) => 1, (6, 7) => 1],
                  [(1, 7) => -1, (5, 6) => 1], [(2, 7) => -1, (4, 6) => -1], [(3, 7) => -1, (4, 5) => 1],
                  [(1, 4) => 1, (2, 5) => 1, (3, 6) => 1]]
    claim("eq:Phi2 as printed (with its signs): the coefficient of x_i in Φ(x, ., .)", as_vector.(paper_Phi2) == phi_linear_forms())
    pfaffians = [pfaffian(matrix(R, A2[[k for k in 1:7 if k != i], [k for k in 1:7 if k != i]])) for i in 1:7]
    claim("up to sign, the 6×6 Pfaffians of Φ(x, ., .) are x_1 q, ..., x_7 q",
          all(i -> pfaffians[i] == x[i] * q || pfaffians[i] == -x[i] * q, 1:7))
    info("the signs: Pf_i = ±x_i q for the Pfaffian without row and column i = 1, ..., 7: " *
         join([pfaffians[i] == x[i] * q ? "+" : "-" for i in 1:7], " "))

    subheading("Lie(Stab Φ) over every field: the COMPUTATION after eq:Phi2 (stored: char-p/adjoint_char.jl)")
    for p in (2, 3, 5, 7)
        K = GF(p)
        sl, gl = first(stabilizer_dimension(K; trace_zero=true)), first(stabilizer_dimension(K))
        check("over GF($p): dim Lie(Stab_SL7(Φ)), dim Lie(Stab_GL7(Φ))" * (p == 3 ? " (the scalars fix Φ in characteristic 3)" : ""),
              [14, p == 3 ? 15 : 14], [sl, gl])
    end
    _, A_sl = stabilizer_dimension(ZZ; trace_zero=true)
    _, A_gl = stabilizer_dimension(ZZ)
    e_sl, e_gl = filter(!iszero, diagonal(snf(A_sl))), filter(!iszero, diagonal(snf(A_gl)))
    check("elementary divisors over ZZ of the SL7 and GL7 systems (35 ones for SL7: dimension 14 over every field)",
          (35, [1], [1, 3]), (length(e_sl), Int.(unique(e_sl)), sort(Int.(unique(e_gl)))))
    for line in readlines(study_path("g2", "char-p", "results", "adjoint_char.txt"))
        startswith(line, "elementary divisors") && stored("the integer systems, by adjoint_char.jl", line)
        occursin("simple", line) && stored("E and Lie(G2), used in Section 8, by adjoint_char.jl", line)
    end

    subheading("The spaces Q, G ⊂ OG(2,7) ⊂ Gr(2,7) and F on which G2 acts")
    cited("the history of G2: found by Engel and Killing, presented by Engel on June 11, 1900 [Agricola; Manivel]")
    Q = load(g2("pointspace", "00_ideal.mrdi"))
    stored_q = only(gens(Q))
    claim("the ideal of the quadric Q ⊂ P^6 is generated by q = x1x4 + x2x5 + x3x6 - x7^2",
          evaluate(stored_q, x) in (q, -q), "stored: $(stored_q)")
    check("\"Both Q and G have dimension 5\": dim Q, from the stored ideal (a hypersurface in P^6)", 5, dim(Q) - 1)
    info("dim G = 5 and dim F = 6 are checked below, with eq:grass1 and with the flag variety")
    I = load(g2("grassmannian", "00_ideal.mrdi"))
    P = base_ring(I)
    names = string.(symbols(P))
    linear = [f for f in gens(I) if total_degree(f) == 1]
    quadrics = [f for f in gens(I) if total_degree(f) == 2]
    plucker(i, j) = P[findfirst(==("p$i$j"), names)]
    subpfaffians = [plucker(i, j) * plucker(k, l) - plucker(i, k) * plucker(j, l) + plucker(i, l) * plucker(j, k)
                    for (i, j, k, l) in Combinatorics.combinations(1:7, 4)]
    Gr = ideal(P, subpfaffians)
    check("dim Gr(2,7) ⊂ P^20", 10, dim(Gr) - 1)
    # for p = u∧v the matrix P·B·P is b(u,v)(uvᵀ + vuᵀ) − b(v,v)uuᵀ − b(u,u)vvᵀ: it vanishes iff the line is isotropic
    skew = matrix(P, [i < j ? plucker(i, j) : (i > j ? -plucker(j, i) : zero(P)) for i in 1:7, j in 1:7])
    N = skew * matrix(P, POLAR) * skew
    isotropy = unique(filter(!iszero, [N[i, j] for i in 1:7 for j in i:7]))
    check("dim OG(2,7), the lines on Q (Gr(2,7) and the entries of P·B·P)", 7, dim(Gr + ideal(P, isotropy)) - 1)
    GI = I + ideal(P, isotropy)
    check("G ⊂ OG(2,7): I + (isotropy quadrics) keeps (affine dimension, degree) of the irreducible G", [6, 18],
          [dim(GI), Int(degree(GI))])
    info("isotropy quadrics (distinct nonzero entries of P·B·P): $(length(isotropy)), of which " *
         "$(count(f -> iszero(normal_form(f, I)), isotropy)) already lie in I")

    subheading("The G2-Grassmannian G = Gr(2,7) ∩ L ⊂ P^20, eq:7linear and eq:grass1")
    claim("the 35 quadrics of I are the 4×4 subpfaffians p_ij p_kl − p_ik p_jl + p_il p_jk (up to sign)",
          length(quadrics) == 35 && all(f -> f in subpfaffians || -f in subpfaffians, quadrics) &&
          all(s -> s in quadrics || -s in quadrics, subpfaffians))
    cited("trop(Gr(2,7)) is the space of phylogenetic trees with 7 leaves [Maclagan–Sturmfels, Theorem 4.3.5]")
    forms = phi_linear_forms()
    stored_forms = [[coeff(f, P[findfirst(==(pair_name(k)), names)]) for k in 1:21] for f in linear]
    paper_7linear = [[(2, 3) => 1, (4, 7) => 1], [(1, 3) => 1, (5, 7) => -1], [(1, 2) => 1, (6, 7) => 1],
                     [(1, 7) => 1, (5, 6) => -1], [(2, 7) => 1, (4, 6) => 1], [(3, 7) => 1, (4, 5) => -1],
                     [(1, 4) => 1, (2, 5) => 1, (3, 6) => 1]]
    claim("eq:7linear as printed: the stored linear forms of I, in this order, up to sign",
          length(stored_forms) == 7 &&
          all(i -> stored_forms[i] in (as_vector(paper_7linear[i]), -as_vector(paper_7linear[i])), 1:7))
    claim("the 7 linear forms eq:7linear are the coefficients of Φ(x, ., .) as a linear form in x",
          rank_of(forms) == 7 && rank_of(vcat(forms, stored_forms)) == 7)
    for f in forms
        info(join(["$(c > 0 ? "+" : "-")$(pair_name(k))" for (k, c) in enumerate(f) if !iszero(c)], " ") * " = 0")
    end
    check("eq:grass1, G = Gr(2,7) ∩ L: generators of I in 21 variables (linear forms, Plücker quadrics)", [7, 35],
          [length(linear), length(quadrics)])
    check("dim G and degree G", [5, 18], [dim(I) - 1, Int(degree(I))])
    for p in (2, 3, 5)
        K = GF(p)
        Pp, _ = polynomial_ring(K, symbols(P))
        Ip = ideal(Pp, [map_coefficients(c -> K(numerator(c)), f; parent=Pp) for f in gens(I)])
        check("over GF($p): dim G and degree G", [5, 18], [dim(Ip) - 1, Int(degree(Ip))])
    end

    subheading("The lines of G cover Q; the flag variety F ⊂ Q × G ⊂ P^6 × P^20")
    J = load(g2("flag", "00_ideal.mrdi"))
    S = base_ring(J)
    # F is irreducible of dimension 6 (stored purity TOML) and q ∈ J, so π(F) ⊂ Q is closed and irreducible, and every
    # nonempty fibre has dimension ≥ 6 − dim π(F)
    Pe, pe = polynomial_ring(QQ, [pair_name(k) for k in 1:21])
    at_e1 = vcat([k == 1 ? one(Pe) : zero(Pe) for k in 1:7], pe)
    fiber = ideal(Pe, [evaluate(f, at_e1) for f in gens(J)])
    check("lines of G through e1 ∈ Q: (projective dimension, degree); 6 − 1 = 5 = dim Q, so the lines cover Q", [1, 1],
          [dim(fiber) - 1, Int(degree(fiber))])
    info("the lines through e1: the coordinates not in the fibre ideal are " *
         join([pair_name(k) for k in 1:21 if !(pe[k] in fiber)], ", ") * ", the pencil e1∧(s e5 + t e6)")
    purity = TOML.parsefile(g2("flag", "00_ideal_purity.toml"))
    stored("\"F has dimension 6\": dim F, by FlagPurityVerifier.jl (data/g2/flag/00_ideal_purity.toml: affine dimension " *
           "$(purity["dimension"]), prime = $(purity["prime"]))", purity["dimension"] - 2; paper=6)
    bidegree(f) = only(unique((sum(e[1:7]), sum(e[8:28])) for e in AbstractAlgebra.exponent_vectors(f)))
    degrees = [bidegree(f) for f in gens(J)]
    # The bilinear generators modulo the products x_i L_j, as vectors in the space of the monomials x_k p_ij.
    bilinear = [f for (f, d) in zip(gens(J), degrees) if d == (1, 1)]
    linear_J = [f for (f, d) in zip(gens(J), degrees) if d == (0, 1)]
    monomials = [S[k] * S[7 + l] for k in 1:7 for l in 1:21]
    vec(f) = [coeff(f, m) for m in monomials]
    products = [vec(S[k] * L) for k in 1:7 for L in linear_J]
    independent = rank_of(vcat(products, vec.(bilinear))) - rank_of(products)
    check("independent bilinear incidence equations modulo the products x_i·(linear forms)", 34, independent)
    rank_mod(vectors, K) = rank(matrix(K, reduce(vcat, permutedims.([[K(numerator(c)) for c in v] for v in vectors]))))
    for p in (2, 3, 5)
        K = GF(p)
        check("over GF($p): independent bilinear incidence equations modulo x_i·(linear forms)", 34,
              rank_mod(vcat(products, vec.(bilinear)), K) - rank_mod(products, K))
    end
    check("the 78 generators of the ideal of F by bidegree (2,0), (0,1), (0,2), (1,1)", [1, 7, 35, 35],
          [count(==(d), degrees) for d in ((2, 0), (0, 1), (0, 2), (1, 1))])
    trinomial(i, j, k) = S[i] * S[7 + PAIR_INDEX[(j, k)]] - S[j] * S[7 + PAIR_INDEX[(i, k)]] + S[k] * S[7 + PAIR_INDEX[(i, j)]]
    trinomials = [trinomial(c...) for c in Combinatorics.combinations(1:7, 3)]
    claim("the 35 bilinear generators are the trinomials x_i p_jk − x_j p_ik + x_k p_ij (up to sign), linearly independent",
          all(f -> f in trinomials || -f in trinomials, bilinear) && rank_of(vec.(bilinear)) == 35)
    claim("the generator of bidegree (2,0) is q", only(f for (f, d) in zip(gens(J), degrees) if d == (2, 0)) == evaluate(q, gens(S)[1:7]))

    subheading("The hexagon eq:hexagon and the Weyl group D12 (Figure fig:shape_hexagon)")
    cited("(Q, G, F) is a generalized hexagon in Tits' theory of buildings [Tits; Van Maldeghem]")
    hexagon = [1, 5, 3, 4, 2, 6]
    hexagon_edges = [Tuple(sort([hexagon[a], hexagon[mod1(a + 1, 6)]])) for a in 1:6]
    unused = [PAIRS[k] for k in 1:21 if all(f -> iszero(f[k]), forms)]
    check("the p_ij in no linear form: the edges of the hexagon e1-e15-e5-e35-e3-e34-e4-e24-e2-e26-e6-e16-e1",
          sort(hexagon_edges), sort(unused))
    flags = [(hexagon[a], Tuple(sort([hexagon[a], hexagon[mod1(a + s, 6)]]))) for a in 1:6 for s in (-1, 1)]
    flag_point(i, ij) = vcat([QQ(k == i ? 1 : 0) for k in 1:7], [QQ(k == PAIR_INDEX[ij] ? 1 : 0) for k in 1:21])
    claim("eq:hexagon: the 12 flags (e_i, e_ij) of the cycle lie on F (the 78 generators vanish)",
          length(unique(flags)) == 12 && all(fl -> all(f -> iszero(evaluate(f, flag_point(fl...))), gens(J)), flags))
    claim("eq:hexagon is non-degenerate (definition in Section 9): its 6 points and 6 lines are distinct",
          length(unique(first.(flags))) == 6 && length(unique(last.(flags))) == 6)
    info("opposite points e1/e4, e5/e2, e3/e6 are non-orthogonal for q: $(all(a -> POLAR[hexagon[a], hexagon[a + 3]] != 0, 1:3))")
    rotation, reflection = [5, 6, 4, 2, 3, 1, 7], [1, 3, 2, 4, 6, 5, 7]
    group = Set([collect(1:7)])
    frontier = [collect(1:7)]
    while !isempty(frontier)
        new = Vector{Int}[]
        for g in frontier, s in (rotation, reflection)
            h = s[g]
            h in group || (push!(group, h); push!(new, h))
        end
        frontier = new
    end
    support(f) = Set(PAIRS[k] for k in 1:21 if !iszero(f[k]))
    act(g, s) = Set(Tuple(sort([g[i], g[j]])) for (i, j) in s)
    claim("Figure fig:shape_hexagon: every g ∈ D12 maps (the support of) the equation labelled i to the one labelled g(i)",
          all(g -> all(i -> act(g, support(forms[i])) == support(forms[g[i]]), 1:7), group))
    colours, shapes = [Set([1, 2, 3]), Set([4, 5, 6])], [Set([1, 4]), Set([2, 5]), Set([3, 6])]
    image_blocks(g, blocks) = Set(Set(g[i] for i in b) for b in blocks)
    claim("D12 permutes the colours {1,2,3}, {4,5,6} and the shapes {1,4}, {2,5}, {3,6} of the labels, and fixes the heart 7",
          all(g -> image_blocks(g, colours) == Set(colours) && image_blocks(g, shapes) == Set(shapes) && g[7] == 7, group))
    info("the D12-orbits on the 21 Plücker coordinates, and the equations (labels) they enter:")
    pair_orbits = unique(sort(unique(Tuple(sort([g[i], g[j]])) for g in group)) for (i, j) in PAIRS)
    for o in sort(pair_orbits; by=length, rev=true)
        labels = sort(unique(i for i in 1:7 for p in o if p in support(forms[i])))
        info("  " * rpad(join(["p$a$b" for (a, b) in o], " "), 26) *
             (isempty(labels) ? "in no equation" : "in L_" * join(labels, ", L_")))
    end
    place = Dict(v => a for (a, v) in enumerate(hexagon))
    triangles = Set(Set(t) for t in keys(PHI) if !(7 in t))
    diagonals = [sort([i for i in t if i != 7]) for t in keys(PHI) if 7 in t]
    claim("Φ = the two triangles of alternate vertices of eq:hexagon + three diagonals (opposite vertices, with e7)",
          triangles == Set([Set(hexagon[1:2:5]), Set(hexagon[2:2:6])]) && length(diagonals) == 3 &&
          all(d -> abs(place[d[1]] - place[d[2]]) == 3, diagonals))
    check("order of the Weyl group D12 = ⟨(1 5 3 4 2 6), (2 3)(5 6)⟩", 12, length(group))
    permutations_of(t) = let m = load(joinpath(TARGET_DIRECTORIES[t], "05_symmetry_taxon_permutations.mrdi"))
        Set([Int(m[i, j]) for j in 1:ncols(m)] for i in 1:nrows(m))
    end
    claim("caption: this D12 is the group of taxon permutations stored with the census of the G2-Dressian, trop(G), the flag Dressian and trop(F)",
          all(t -> permutations_of(t) == group, ("dressian", "grassmannian", "flag_dressian", "flag")))

    subheading("eq:grass2: trop(G) ⊊ trop(Gr(2,7)) ∩ trop(L), the G2-Dressian; the flag Dressian")
    claim("the 7 linear forms have disjoint supports, so they are the circuits of L, and the G2-Dressian is the prevariety of the 7 + 35 generators of I",
          sum(length(support(f)) for f in forms) == length(reduce(union, support.(forms))))
    D, FG = fan("dressian"), fan("grassmannian")
    ones21 = fill(QQ(1), 21)
    claim("both are fans in R^21/1: ambient dimension 21, and 1 in the lineality space",
          all(F -> ambient_dim(F) == 21 && rank_of(vcat(last(fan_rays(F)), [ones21])) == rank_of(last(fan_rays(F))), (D, FG)))
    gr, dr = summary("grassmannian")["complex"], summary("dressian")["complex"]
    check("trop(G), G2-Dressian: (lineality in R^21 with 1, dimension of the complex modulo lineality, pure)",
          [(3, 2, true), (3, 3, false)], [(c["lineality_dimension"], c["dimension"], c["pure"]) for c in (gr, dr)])
    inner_point(C) = QQ.(collect(relative_interior_point(C)))
    LD, LG = locator(D), locator(FG)
    claim("trop(G) ⊂ G2-Dressian: an interior point of each maximal cone of trop(G) lies in a cone of the Dressian",
          all(C -> !isempty(locate_closed(LD, inner_point(C))), maximal_cones(FG)))
    # 3-simplices modulo lineality are cones of dimension lineality + 4
    tetrahedra = [C for C in maximal_cones(D) if dim(C) == lineality_dim(D) + 4]
    check("the inclusion is strict: tetrahedra of the Dressian, and those with an interior point in trop(G)", [3, 0],
          [length(tetrahedra), count(C -> !isempty(locate_closed(LG, inner_point(C))), tetrahedra)])
    FF = fan("flag")
    _, flag_lineality = fan_rays(FF)
    ones_x, ones_p = [QQ(k <= 7 ? 1 : 0) for k in 1:28], [QQ(k > 7 ? 1 : 0) for k in 1:28]
    check("trop(F) ⊂ R^7/1 × R^21/1: ambient dimension, and both all-ones vectors in its lineality space", (28, true),
          (ambient_dim(FF), rank_of(vcat(flag_lineality, [ones_x, ones_p])) == rank_of(flag_lineality)))
    provenance = TOML.parsefile(g2("flag_dressian", "provenance", "tropicalize.toml"))
    stored("\"the G2 flag Dressian is the tropical prevariety defined by the 78 generators of the ideal of F\": generators " *
           "(data/g2/flag_dressian/provenance/tropicalize.toml)", provenance["metadata"]["original_generators"]; paper=78)
    info("its inputs: " * join([i["path"] for i in provenance["inputs"]], ", "))
    # the census stamps its inputs with TropicalGeometryG2.artifact_digest, the sha256 of the file
    recorded = only(i["sha256"] for i in provenance["inputs"] if i["path"] == "data/g2/flag/00_ideal.mrdi")
    current = TropicalGeometryG2.artifact_digest(g2("flag", "00_ideal.mrdi"))
    info("the sha256 of data/g2/flag/00_ideal.mrdi recorded there: " * (recorded == current ? "that of the current file" :
         "$(recorded[1:12])..., not that of the current file, $(current[1:12])... (an older serialization)"))
    info("the four objects of the introduction (stored 08_summary.toml; dimension and f-vector modulo lineality):")
    info(@sprintf("  %-28s %-8s %-10s %-10s %-6s %-26s %s", "", "ambient", "lineality", "dimension", "pure", "f-vector", "group"))
    for (label, target, ambient) in (("G2-Dressian", "dressian", 21), ("trop(G)", "grassmannian", 21),
                                     ("G2 flag Dressian", "flag_dressian", 28), ("trop(F)", "flag", 28))
        c = s1_stored_complex(target)
        info(@sprintf("  %-28s %-8d %-10d %-10d %-6s %-26s %d", label, ambient, c["lineality_dimension"], c["dimension"],
                      c["pure"], show_value(c["f_vector"]), c["group_order"]))
    end

    subheading("Organization of the paper: forward statements")
    fg, fg2, ff, ff2 = (s1_stored_complex(t)["f_vector"] for t in ("grassmannian", "grassmannian_gf2", "flag", "flag_gf2"))
    stored("(Section 4) \"they have different tropicalization in characteristic p=2\": f-vectors of trop(G), trop(F) over " *
           "QQ and GF(2) ($fg vs $fg2; $ff vs $ff2; stored 08_summary.toml) differ", fg != fg2 && ff != ff2; paper=true)
    # X e_i = Σ_m X[m, i] e_m; the stabilizer of the hexagon fixes the lines e_i ∧ e_i' iff it fixes the six points
    offdiagonal = [(m, i) for i in 1:6 for m in 1:7 if m != i]
    M = matrix(QQ, [X[mi[1], mi[2]] for X in algebra, mi in offdiagonal])
    check("dim H = dim G2 − dim of the stabilizer of the six points of eq:hexagon in Lie(G2), and that stabilizer", [12, 2],
          [rank(M), length(algebra) - rank(M)])
    _, cartan = nullspace(transpose(M))
    torus = [sum(cartan[b, c] .* algebra[b] for b in 1:length(algebra)) for c in 1:ncols(cartan)]
    info("the stabilizer of eq:hexagon in Lie(G2): " *
         join(["diag(" * join(string.([X[i, i] for i in 1:7]), ", ") * ")" for X in torus], " and ") *
         (all(X -> all(iszero(X[i, j]) for i in 1:7 for j in 1:7 if i != j), torus) ? ", diagonal" : ", NOT diagonal"))
    cited("the canonical model of a general curve of genus 10 on a K3 surface is Λ ∩ G, for a general Λ of codimension 4 [Mukai]")
    check("Λ ∩ L ≃ P^9 for a general Λ of codimension 4: dim L = 20 − (rank of the 7 forms), minus 4", 9, 20 - rank_of(forms) - 4)
end
