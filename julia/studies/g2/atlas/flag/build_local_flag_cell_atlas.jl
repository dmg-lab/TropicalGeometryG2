function local_flag_title_page(io, pages, contexts, ray_orbits)
    support(page, field) = field == :qq ?
        (page.qq === nothing ? nothing : contexts.qq.census.supports[page.qq]) :
        (page.gf2 === nothing ? nothing : contexts.gf2.census.supports[page.gf2])
    toric(page, field) = support(page, field) !== nothing && support(page, field).toric
    any_support(page) = something(support(page, :qq), support(page, :gf2))
    chevalley = join((
        "  The Chevalley polytope of \\(G_2/P_2\\) is \\($(census_polytope_tex(page.label))\\)."
        for page in pages if any_support(page).chevalley
    ))
    toric_both = count(page -> toric(page, :qq) && toric(page, :gf2), pages)
    toric_qq = count(page -> toric(page, :qq) && !toric(page, :gf2), pages)
    toric_gf2 = count(page -> !toric(page, :qq) && toric(page, :gf2), pages)
    others = [page for page in pages if !toric(page, :qq) && !toric(page, :gf2)]
    other_both = count(page -> page_fields(page) == (:qq, :gf2), others)
    other_qq = count(page -> page_fields(page) == (:qq,), others)
    other_gf2 = count(page -> page_fields(page) == (:gf2,), others)
    simplices = count(page -> toric(page, :qq) && toric(page, :gf2) &&
                              first(any_support(page).complexity) == 1, pages)
    other_simplices = simplices == 1 ? "the other simplex" : "the other simplices"
    triangles = count(page -> page.spec.kind == :triangle, pages)
    squares = count(page -> page.spec.kind == :square, pages)
    new_orbits = [number for (number, orbit) in enumerate(ray_orbits)
                  if minimum(orbit) > nrows(contexts.qq.rays)]
    new_rays = join(("R_{$ray}" for number in new_orbits for ray in ray_orbits[number]), ",\\,")
    # Central points other than the plain ray sum, stated here instead of on
    # their pages.
    exceptions = String[]
    for page in pages
        context, orbit = page.qq === nothing ? (contexts.gf2, page.gf2) : (contexts.qq, page.qq)
        sample = context.samples[orbit]
        any(!=(1), sample.coefficients) && push!(exceptions,
            "$(page.spec.kind) orbit $(page.label): \\($(local_central_point_tex(page.spec, sample))\\)")
    end
    centre = isempty(exceptions) ? "" : " (" * join(exceptions, "; ") * ")"
    tuple_tex(values) = "(" * join(values, ",") * ")"
    print(io, """\\thispagestyle{empty}
\\begin{center}\\vspace*{4mm}
