\\end{center}\\vspace{10mm}
\\begin{atlasbox}
\\begin{atlaspanel}
{\\Large\\bfseries How to read a page}\\par\\vspace{3mm}
\\begin{tabularx}{\\linewidth}{@{}>{\\bfseries}l@{\\hspace{5mm}}X@{}}
Orbit labels & Support orbits are labelled 1--$(length(pages)).  Those with a
toric degeneration come first: over both fields ($toric_both orbits: the Chevalley
