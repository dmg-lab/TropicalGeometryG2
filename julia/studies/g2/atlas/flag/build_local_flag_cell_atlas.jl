function local_polygon_data(spec, construction)
    if spec.kind == :triangle
        order = collect(spec.representative)
        positions = [(0.0, 9.45), (-10.15, -8.30), (10.15, -8.30)]
        return (
            order=order,
            positions=positions,
            nonedges=Tuple{Int,Int}[],
            note="All three pairs are boundary edges.",
        )
    end

    merge_lookup = Dict(merge.square => merge for merge in construction.merges)
    merge = merge_lookup[spec.representative]
    diagonal = collect(merge.diagonal)
    opposite = sort!(collect(setdiff(Set(spec.representative), Set(diagonal))))
    length(opposite) == 2 || error("square does not have two complementary vertices")
    order = [diagonal[1], opposite[1], diagonal[2], opposite[2]]
    source_edges = Set{Tuple{Int,Int}}()
    for triangle in merge.triangles
        for left_index in 1:2, right_index in (left_index + 1):3
            push!(source_edges, Tuple(sort((triangle[left_index], triangle[right_index]))))
        end
    end
    delete!(source_edges, merge.diagonal)
    boundary_edges = Set(
        Tuple(sort((order[index], order[index == 4 ? 1 : index + 1])))
        for index in 1:4
    )
    boundary_edges == source_edges ||
        error("derived square boundary disagrees with its two source triangles")
    nonedges = [Tuple(sort(diagonal)), Tuple(sort(opposite))]
    positions = [(-10.15, 8.75), (10.15, 8.75), (10.15, -8.75), (-10.15, -8.75)]
    note = "Both diagonals are non-edges of the square."
    return (order=order, positions=positions, nonedges=nonedges, note=note)
end

function local_prefixed_coordinates(
    tree,
    prefix::String,
    centre,
    radius::Float64;
    bounded_edge_scale::Float64=1.0,
)
    0 < bounded_edge_scale <= 1 || error("bounded-edge scale must lie in (0,1]")
    base = symmetric_layout(tree; radius=radius)
    if bounded_edge_scale != 1.0
        internal = sort([vertex for vertex in keys(tree.adjacency) if vertex > tree.ntaxa])
        centre_x = sum(base[vertex][1] for vertex in internal) / length(internal)
        centre_y = sum(base[vertex][2] for vertex in internal) / length(internal)
        for vertex in internal
            x, y = base[vertex]
            base[vertex] = (
                centre_x + bounded_edge_scale * (x - centre_x),
                centre_y + bounded_edge_scale * (y - centre_y),
            )
        end
    end
    coordinates = Dict{Int,Tuple{Float64,Float64}}()
    for vertex in keys(base)
        x, y = base[vertex]
        coordinates[vertex] = (x + centre[1], y + centre[2])
    end
    return coordinates, Dict(vertex => "$prefix-v$vertex" for vertex in keys(base))
end

function local_declare_coordinates(io, coordinates, names)
    for vertex in sort!(collect(keys(coordinates)))
        x, y = coordinates[vertex]
        println(io, @sprintf("\\coordinate (%s) at (%.5f,%.5f);", names[vertex], x, y))
    end
end

function local_write_taxa(io, tree, names)
    for taxon in 1:tree.ntaxa
        println(io, "\\$(FLAG_TREE_TAXON_MACROS[taxon]){$(names[taxon])}")
    end
end

function local_write_minimal_tree(
    io,
    grass_ray,
    centre,
    ray_lifts;
    prefix::String,
    radius::Float64=LOCAL_MINIMAL_RADIUS,
    pendant_length_position::Float64=0.50,
    internal_vertex_style::String="lettered vertex",
    bounded_edge_scale::Float64=1.0,
)
    tree = ray_lifts.records[grass_ray].tree
    coordinates, names = local_prefixed_coordinates(
        tree, prefix, centre, radius; bounded_edge_scale=bounded_edge_scale,
    )
    local_declare_coordinates(io, coordinates, names)
    for (left, right, edge_length) in flag_tree_edges(tree)
        pendant = left <= tree.ntaxa || right <= tree.ntaxa
        style = pendant ? "pendant edge" : "internal edge"
        position = pendant ? pendant_length_position : 0.50
        println(
            io,
            "\\draw[$style] ($(names[left]))--" *
            "node[mini length,pos=$position] {\\($(tex_rational(edge_length))\\)}" *
            "($(names[right]));",
        )
    end
    for vertex in sort([vertex for vertex in keys(tree.adjacency) if vertex > tree.ntaxa])
        letter = ray_lifts.letters[grass_ray][vertex]
        println(io, "\\node[$internal_vertex_style] at ($(names[vertex])) {$letter};")
    end
    local_write_taxa(io, tree, names)
    return coordinates
end

function local_ray_orbit_members_tex(orbit)
    members = sort!(collect(orbit))
    representative = first(members)
    labels = [member == representative ? "\\underline{$member}" : string(member)
              for member in members]
    return join(labels, ", ")
end

function local_support_orbit_members_tex(members; per_row::Int=4)
    entries = ["\\(" * clean_tex_set(member) * "\\)" for member in members]
    chunks = [entries[index:min(index + per_row - 1, length(entries))]
              for index in 1:per_row:length(entries)]
    rows = join((join(chunk, ",\\quad ") for chunk in chunks), "\\\\")
    return "\\shortstack[l]{$rows}"
end

function local_support_orbit_members_inline_tex(members, representative)
    count(==(representative), members) == 1 || error("support representative must occur once")
    entries = [
        "\\(" * (member == representative ?
            "\\underline{" * clean_tex_set(member) * "}" : clean_tex_set(member)) * "\\)"
        for member in members
    ]
    return join(entries, ", ")
end

function local_write_ray_orbit_card(io, orbit_number, orbit, ray_lifts; slot_fraction, fields)
    representative = minimum(orbit)
    presence = fields == (:qq, :gf2) ? "" : "$(local_presence_tex(fields))\\quad"
    println(io, "\\begin{minipage}[t][$slot_fraction\\textheight][t]{\\linewidth}")
    println(io, raw"\centering\vspace{0pt}\begin{tikzpicture}")
    println(io, raw"\node[atlas box,inner xsep=1.8mm,inner ysep=1.2mm,text width=.94\linewidth,align=left] {%")
    println(io, raw"\AtlasOrbitSplit{%")
    println(io, "\\vspace*{-2mm}\\mbox{{\\large\\bfseries [O$orbit_number]}\\hspace{3mm}" *
                "{\\small\\color{muted}size $(length(orbit))}}%")
    println(io, raw"}{%")
    members = local_ray_orbit_members_tex(orbit)
    println(io, "{\\small$presence{\\color{muted}$members}\\rule[-3mm]{0pt}{3mm}}%")
    println(io, raw"}%")
    println(io, raw"};")
    println(io, raw"\end{tikzpicture}\par\vspace{0mm}")
    println(io, raw"\begin{tikzpicture}[x=1cm,y=1cm]")
    local_write_minimal_tree(
        io,
        representative,
        (0.0, 0.0),
        ray_lifts;
        prefix="orbit-$orbit_number",
        radius=3.10,
        pendant_length_position=0.50,
        internal_vertex_style="orbit lettered vertex",
        bounded_edge_scale=LOCAL_ORBIT_BOUNDED_EDGE_SCALE,
    )
    println(io, raw"\end{tikzpicture}")
    println(io, raw"\end{minipage}\par")
end

"""
One card per ray orbit, four to a column. The first `common_orbits` orbits
occur over both fields and the following ones only over GF(2).
"""
function local_write_ray_orbit_page(io, ray_orbits, ray_lifts, common_orbits::Int)
    columns = collect(Iterators.partition(eachindex(ray_orbits), 4))
    length(columns) <= 3 || error("the ray orbit page holds at most twelve orbits")
    println(io, raw"\clearpage")
    println(io, raw"\vspace*{-7mm}")
    println(io, "{\\LARGE\\bfseries Minimal \$G_2\$-ray Weyl representatives}\\hfill" *
                "{\\small\\color{muted}$(length(ray_orbits)) representatives for " *
                "$(sum(length, ray_orbits)) rays}\\par\\vspace{-2mm}")
    for (column_number, orbit_numbers) in enumerate(columns)
        println(io, raw"\begin{minipage}[t]{0.318\textwidth}\vspace{0pt}")
        for orbit_number in orbit_numbers
            local_write_ray_orbit_card(
                io, orbit_number, ray_orbits[orbit_number], ray_lifts;
                slot_fraction="0.228",
                fields=orbit_number <= common_orbits ? (:qq, :gf2) : (:gf2,),
            )
        end
        println(io, raw"\end{minipage}")
        column_number < length(columns) && println(io, raw"\hfill")
    end
end

function local_piece_occurrences_tex(piece)
    isempty(piece.pages) && return "Flag Minkowski summands only."
    return "In " * join(
        ("\\($(census_polytope_tex(position))\\)" for position in piece.pages),
        ", ",
    ) * "."
end

function local_write_piece_card(io, piece; width::String, drawing_height::Float64)
    title_font, text_font = piece.dimension == 3 ? (raw"\LARGE", raw"\large") :
                                                   (raw"\Large", raw"\normalsize")
    println(io, "\\begin{minipage}[t]{$width\\textwidth}\\begin{atlaspanel}")
    println(
        io,
        "{$title_font\\bfseries \\($(piece.tex)\\)}\\hspace{3mm}" *
        "{$text_font\\color{muted}$(piece.label)}\\hfill" *
        "{$text_font\\(f=$(census_f_vector_tex(piece.f_vector))\\)}\\par\\vspace{3mm}",
    )
    println(io, "\\begin{minipage}[c][$(drawing_height)cm][c]{\\linewidth}\\centering")
    print(io, piece.tikz)
    println(io, raw"\end{minipage}\par\vspace{3mm}")
    println(io, "{\\color{muted}$(local_piece_occurrences_tex(piece))}")
    println(io, raw"\end{atlaspanel}\end{minipage}")
end

function local_write_smallest_piece_page(io, pieces)
    isempty(pieces) && error("no smallest piece of dimension three or four to draw")
    println(io, raw"\clearpage")
    println(io, raw"\vspace*{-7mm}")
    println(io, raw"{\LARGE\bfseries Smallest pieces}\hfill{\small\color{muted}drawn by polymake}\par\vspace{3mm}")
    # Three-polytopes two per row as solids, 4-polytopes three per row as
    # Schlegel diagrams.
    for (dimension, per_row, width, drawing_height) in ((3, 2, ".485", 13.0), (4, 3, ".323", 8.0))
        row = [piece for piece in pieces if piece.dimension == dimension]
        for (index, piece) in enumerate(row)
            local_write_piece_card(io, piece; width, drawing_height)
            last_in_row = index % per_row == 0 || index == length(row)
            println(io, last_in_row ? raw"\par\vspace{4mm}" : raw"\hfill")
        end
    end
