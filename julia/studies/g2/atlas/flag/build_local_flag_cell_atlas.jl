"""
The flag cells of a page in each of its fields, by tree location. Over a
support cell present in both fields, both must give the same cells.
"""
function local_page_entries(page, contexts)
    entries = Any[]
    for (context, orbit) in ((contexts.qq, page.qq), (contexts.gf2, page.gf2))
        orbit === nothing && continue
        sample = context.samples[orbit]
        coordinates = symmetric_layout(sample.tree; radius=LOCAL_CENTRAL_RADIUS)
        items = local_central_items(sample, coordinates, context.flag_data, context.ray_lifts)
        push!(entries, (
            context=context, orbit=orbit, sample=sample, items=items,
            by_location=Dict(item.location => item for item in items),
        ))
    end
    if length(entries) == 2
        left, right = entries[1].by_location, entries[2].by_location
        keys(left) == keys(right) && all(
            left[location].tuple == right[location].tuple &&
            left[location].cell_type.name == right[location].cell_type.name
            for location in keys(left)
        ) || error("support orbit $(page.label) has different flag cells over QQ and over GF(2)")
    end
    return entries
end

"""
The summand lines of the prime edge cells of a page, by tree location. A line
carries its field only when the two fields of the page disagree.
"""
function local_page_summand_lines(entries, label_of)
    lines = Dict{String,Vector{String}}()
    for item in first(entries).items
        item.kind == :edge || continue
        texts = Pair{Symbol,String}[]
        for entry in entries
            cell = entry.by_location[item.location].cell
            summand = get(entry.context.census.summands, cell, nothing)
            summand === nothing && continue
            field = entry.context.field
            push!(texts, field => (summand.slice_tex === nothing ? "\\text{prime, not toric}" :
                summand.slice_tex * "+" * census_polytope_tex(label_of[(field, summand.support)])))
        end
        isempty(texts) && continue
        agree = length(texts) == length(entries) && length(unique(last.(texts))) == 1
        lines[item.location] = agree ? [last(first(texts))] :
            ["$(field_tex(field))\\colon\\;$text" for (field, text) in texts]
    end
    return lines
end

"The status line of a page; one line per field only when the fields disagree."
function local_page_status_tex(page, entries)
    texts = [census_support_summary_tex(entry.context.census.supports[entry.orbit], page.label)
             for entry in entries]
    length(unique(texts)) == 1 && return first(texts)
    return join(("\\($(field_tex(entry.context.field))\\):\\enspace $text"
                 for (entry, text) in zip(entries, texts)), "\\\\[1mm]")
end

function local_write_orbit_page(
    io,
    page,
    entries,
    construction,
    label_of,
    ray_orbit_of,
)
    spec = page.spec
    # Both fields draw the same cells; the geometry is taken from the first.
    context, sample = first(entries).context, first(entries).sample
    kind = spec.kind == :triangle ? "Triangle" : "Square"
    println(io, raw"\clearpage")
    println(io, raw"\begin{atlaspanel}[top=1mm,bottom=2mm]")
    println(io, raw"\AtlasSupportOrbitSplit{%")
    println(io, "\\vspace*{-3mm}\\mbox{{\\LARGE\\bfseries $kind orbit $(page.label)}" *
                "\\hspace{3mm}\\raisebox{.8mm}[0pt][0pt]{{\\fontsize{16}{18}" *
                "\\selectfont\\color{muted}size $(length(spec.members))}}}%")
    println(io, raw"}{%")
    members = local_support_orbit_members_inline_tex(spec.members, spec.representative)
    println(io, "\\vspace*{-3mm}{\\fontsize{13}{16}\\selectfont" *
                "$(local_presence_tex(page_fields(page)))\\quad{\\color{muted}" *
                "$members}\\rule[-3mm]{0pt}{3mm}}%")
    println(io, raw"}%")
    println(io, raw"\end{atlaspanel}\vspace{2mm}")

    polygon = local_polygon_data(spec, construction)
    println(io, raw"\begin{center}\begin{tikzpicture}[x=1cm,y=1cm]")
    println(io, @sprintf(
        "\\path[use as bounding box] (%.2f,%.2f) rectangle (%.2f,%.2f);",
        -LOCAL_FIGURE_X, -LOCAL_FIGURE_Y, LOCAL_FIGURE_X, LOCAL_FIGURE_Y,
    ))
    polygon_path = join((@sprintf("(%.5f,%.5f)", point[1], point[2])
                         for point in polygon.positions), "--")
    println(io, "\\path[support cell] $polygon_path--cycle;")
    for position in polygon.positions
        println(
            io,
            @sprintf(
                "\\path[vertex disc] (%.5f,%.5f) circle[radius=%.5fcm];",
                position[1], position[2], LOCAL_VERTEX_DISC_RADIUS,
            ),
        )
    end

    for (position_index, (grass_ray, position)) in enumerate(zip(polygon.order, polygon.positions))
        local_write_minimal_tree(
            io, grass_ray, position, context.ray_lifts; prefix="corner-$position_index",
        )
        label = local_ray_label_position(position)
        ray_orbit = ray_orbit_of[grass_ray]
        println(
            io,
            @sprintf(
                "\\node[ray title] at (%.5f,%.5f) {\\(R_{%d}\\;[\\mathrm{O}%d]\\)};",
                label[1], label[2], grass_ray, ray_orbit,
            ),
        )
    end
    callout_shift = spec.kind == :triangle ? LOCAL_TRIANGLE_CALLOUT_SHIFT : 0.0
    tree_centre = spec.kind == :triangle ? (0.0, LOCAL_TRIANGLE_TREE_SHIFT) : (0.0, 0.0)
    items = local_write_central_tree(
        io,
        sample,
        context.flag_data,
        context.ray_lifts;
        summand_lines=local_page_summand_lines(entries, label_of),
        callout_shift=callout_shift,
        centre=tree_centre,
    )
    println(io, raw"\end{tikzpicture}\end{center}\vspace{-1mm}")

    println(io, raw"\begin{atlasbox}\begin{atlaspanel}")
    println(io, local_page_status_tex(page, entries))
    println(io, raw"\end{atlaspanel}\end{atlasbox}")
    return items, polygon
end

function local_write_csv(
    path,
    pages,
    page_entries,
    construction,
    ray_orbit_of,
    prevariety_tetrahedron_orbit,
)
    open(path, "w") do io
        println(io, "label,fields,qq_orbit,gf2_orbit,kind,support,polygon_order,polygon_ray_orbits,location_kind,location,length,polytope,qq_flag_rays,gf2_flag_rays,symbolic_vertices")
        for (page, entries) in zip(pages, page_entries)
            spec = page.spec
            polygon = local_polygon_data(spec, construction)
            polygon_ray_orbits = [ray_orbit_of[ray] for ray in polygon.order]
            function flag_rays(field, location)
                index = findfirst(entry -> entry.context.field == field, entries)
                return index === nothing ? Int[] : entries[index].by_location[location].rays
            end
            for item in first(entries).items
                println(io, join([
                    page.label,
                    join(page_fields(page), '+'),
                    something(page.qq, ""),
                    something(page.gf2, ""),
                    spec.kind,
                    clean_quoted(spec.representative),
                    clean_quoted(polygon.order),
                    clean_quoted(polygon_ray_orbits),
                    item.kind,
                    clean_quoted([item.location]),
                    item.kind == :edge ? string(item.length) : "",
                    clean_quoted([item.cell_type.name]),
                    clean_quoted(flag_rays(:qq, item.location)),
                    clean_quoted(flag_rays(:gf2, item.location)),
                    clean_quoted([item.tuple]),
                ], ','))
            end
        end
        representative = prevariety_tetrahedron_orbit.representative
        println(io, join([
            "E1",
            "prevariety",
            "",
            "",
            :tetrahedron,
            clean_quoted(representative),
            clean_quoted(representative),
            clean_quoted([ray_orbit_of[ray] for ray in representative]),
            :none,
            clean_quoted(["prevariety-only relative interior"]),
            "",
            clean_quoted(["no tropical-flag fiber"]),
            clean_quoted(Int[]),
            clean_quoted(Int[]),
            clean_quoted(String[]),
        ], ','))
    end
end

function local_compile_atlas_pdf(tex_path, pdf_path)
    pdflatex = Sys.which("pdflatex")
    pdflatex === nothing && error("pdflatex is required to compile the G2-tree atlas")
    mkpath(LOCAL_ATLAS_BUILD_DIR)
    mkpath(dirname(pdf_path))
    base_command = Cmd([
        pdflatex, "-interaction=nonstopmode", "-halt-on-error", "-file-line-error",
        "-output-directory=$LOCAL_ATLAS_BUILD_DIR", basename(tex_path),
    ])
    command = Cmd(base_command; dir=dirname(tex_path))
    run(command)
    run(command)
    compiled = joinpath(
        LOCAL_ATLAS_BUILD_DIR,
        replace(basename(tex_path), r"\.tex$" => ".pdf"),
    )
    isfile(compiled) || error("LaTeX compilation did not produce $compiled")
    cp(compiled, pdf_path; force=true)
    return pdf_path
end

function build_local_flag_cell_atlas(; compile_pdf::Bool=true)
    isfile(CLEAN_ATLAS_FAN) || error("build the clean census first: $CLEAN_ATLAS_FAN")
    isfile(GF2_FLAG_FAN) || error("run the GF(2) flag census first: $GF2_FLAG_FAN")
    variety_fan = load(DEFAULT_BALANCED_FAN_PATH)
    balanced_rays = Matrix{QQFieldElem}(load(DEFAULT_BALANCED_RAYS_PATH))
    prevariety_data = prevariety_only_cone_data(variety_fan, balanced_rays)
    prevariety_tetrahedron_orbit = only(filter(
        orbit -> orbit.kind == :tetrahedron,
        prevariety_data.orbits,
    ))
    prevariety_tetrahedron_record =
        prevariety_data.records[prevariety_tetrahedron_orbit.representative]
    construction = support_maximal_cells(variety_fan)
    qq_specs = support_cell_orbit_specs(construction)
    qq_ray_orbits = load_index_orbits(RAY_ORBITS_CSV, :ray)
    gf2_support = gf2_support_data(balanced_rays, qq_specs, qq_ray_orbits)
    ray_orbits = gf2_support.ray_orbits
    ray_orbit_of = Dict(
        ray => orbit_number
        for (orbit_number, orbit) in enumerate(ray_orbits)
        for ray in orbit
    )

    pieces = Dict{String,Any}()
    contexts = (
        qq=local_field_context(:qq, load(CLEAN_ATLAS_FAN), balanced_rays, qq_specs, pieces),
        gf2=local_field_context(:gf2, load(GF2_FLAG_FAN), gf2_support.rays, gf2_support.specs,
                                pieces; ray_index=gf2_support.ray_index),
    )
    pages = census_pages(qq_specs, gf2_support.specs,
                         contexts.qq.census.supports, contexts.gf2.census.supports)
    census_verify_common_polytopes(pages, contexts.qq.census, contexts.gf2.census)
    label_of = Dict{Tuple{Symbol,Int},String}()
    position_of = Dict{Tuple{Symbol,Int},Int}()
    for page in pages, (field, orbit) in ((:qq, page.qq), (:gf2, page.gf2))
        orbit === nothing && continue
        label_of[(field, orbit)] = page.label
        position_of[(field, orbit)] = page.position
    end
    drawn_pieces = census_drawn_pieces(pieces, position_of)
    page_entries = [local_page_entries(page, contexts) for page in pages]
    println("pages: $(length(pages)); drawn smallest pieces: $(length(drawn_pieces))")
    # The QQ certificate of the omitted node triangles is kept with the atlas.
    local_intersection_certificate(contexts.qq.samples, contexts.qq.flag_data, contexts.qq.ray_lifts)
    # The centre of the prevariety tetrahedron is a ray only over GF(2).
    tetrahedron = Set(prevariety_tetrahedron_orbit.representative)
    centres = unique(only(setdiff(member, tetrahedron))
                     for spec in gf2_support.specs if spec.qq_orbit === nothing
                     for member in spec.members if length(intersect(member, tetrahedron)) == 2)
    tetrahedron_centre = only(centres)

    all_items = Any[]
    open(LOCAL_FLAG_CELL_TEX, "w") do io
        local_flag_cell_preamble(io)
        local_flag_title_page(io, pages, contexts, ray_orbits)
        local_write_ray_orbit_page(io, ray_orbits, contexts.gf2.ray_lifts, length(qq_ray_orbits))
        local_write_smallest_piece_page(io, drawn_pieces)
        for (page, entries) in zip(pages, page_entries)
            items, _ = local_write_orbit_page(
                io, page, entries, construction, label_of, ray_orbit_of,
            )
            append!(all_items, items)
        end
        local_write_prevariety_tetrahedron_page(
            io,
            prevariety_tetrahedron_orbit,
            prevariety_tetrahedron_record,
            contexts.qq.ray_lifts,
            ray_orbit_of,
            tetrahedron_centre,
        )
        println(io, raw"\end{document}")
    end
    local_write_csv(
        LOCAL_FLAG_CELL_CSV,
        pages,
        page_entries,
        construction,
        ray_orbit_of,
        prevariety_tetrahedron_orbit,
    )

    edge_cells = [item for item in all_items if item.kind == :edge]
    node_cells = [item for item in all_items if item.kind == :node]
    pdf = compile_pdf ? local_compile_atlas_pdf(LOCAL_FLAG_CELL_TEX, LOCAL_FLAG_CELL_PDF) : nothing
    println("local-cell atlas TeX: ", LOCAL_FLAG_CELL_TEX)
    println("local-cell atlas CSV: ", LOCAL_FLAG_CELL_CSV)
    pdf === nothing || println("local-cell atlas PDF: ", pdf)
    println("coverage: a ray page, a smallest-piece page, ",
            count(page -> page.spec.kind == :triangle, pages), " triangle pages, ",
            count(page -> page.spec.kind == :square, pages), " square page(s), ",
            "and one prevariety tetrahedron page; ",
            count(page -> page_fields(page) == (:qq, :gf2), pages), " orbits over both fields, ",
            count(page -> page_fields(page) == (:qq,), pages), " only over QQ, ",
            count(page -> page_fields(page) == (:gf2,), pages), " only over GF(2)")
    println("central callouts: $(length(edge_cells)) edge cells and $(length(node_cells)) node cells")
    return (
        tex=LOCAL_FLAG_CELL_TEX,
        csv=LOCAL_FLAG_CELL_CSV,
        pdf=pdf,
        pages=pages,
        contexts=contexts,
        items=all_items,
        prevariety_tetrahedron=(
            orbit=prevariety_tetrahedron_orbit,
            record=prevariety_tetrahedron_record,
        ),
    )
end

