function local_edge_length(tree, left::Int, right::Int)
    for (neighbor, edge_length) in tree.adjacency[left]
        neighbor == right && return QQ(edge_length)
    end
    error("vertices $left and $right are not adjacent")
end

function local_flag_type(kind::Symbol, number_of_vertices::Int)
    if kind == :node
        number_of_vertices == 3 && return (name="triangle", symbol="\\triangle", exceptional=false)
        number_of_vertices == 4 && return (name="square", symbol="\\square", exceptional=true)
    elseif kind == :edge
        number_of_vertices == 4 && return (name="tetrahedron", symbol="\\mathrm{tet}", exceptional=false)
        number_of_vertices == 5 && return (name="square pyramid", symbol="\\mathrm{pyr}", exceptional=true)
        number_of_vertices == 6 && return (name="triangular prism", symbol="\\mathrm{prism}", exceptional=true)
    end
    error("unexpected $kind flag cell with $number_of_vertices vertices")
end

function local_flag_vertex_tex(flag_ray::Int, flag_data, ray_lifts)
    grass_ray = flag_data.ray_matches[flag_ray]
    grass_ray == 0 && return "e_{$(ray_lifts.vertical_taxon[flag_ray])}"
    vertex = ray_lifts.flag_to_vertex[flag_ray]
    letter = ray_lifts.letters[grass_ray][vertex]
    return "R_{$grass_ray}^{$letter}"
end

function local_flag_vertex_sort_key(flag_ray::Int, flag_data, ray_lifts)
    grass_ray = flag_data.ray_matches[flag_ray]
    grass_ray == 0 && return (1, ray_lifts.vertical_taxon[flag_ray], "")
    vertex = ray_lifts.flag_to_vertex[flag_ray]
    letter = string(ray_lifts.letters[grass_ray][vertex])
    return (0, grass_ray, letter)
end

function local_flag_cell_tuple_tex(flag_rays, flag_data, ray_lifts)
    ordered_flag_rays = sort!(
        collect(flag_rays);
        by=flag_ray -> local_flag_vertex_sort_key(flag_ray, flag_data, ray_lifts),
    )
    return flag_tree_tex_tuple(
        [local_flag_vertex_tex(flag_ray, flag_data, ray_lifts)
         for flag_ray in ordered_flag_rays],
    )
end

function local_central_items(sample, coordinates, flag_data, ray_lifts)
    items = Any[]
    for slice in sample.slices
        left, right = flag_tree_exception_endpoints(sample.tree, slice.portion)
        left_xy, right_xy = coordinates[left], coordinates[right]
        anchor = ((left_xy[1] + right_xy[1]) / 2, (left_xy[2] + right_xy[2]) / 2)
        cell_type = local_flag_type(:edge, length(slice.flag_rays))
        push!(items, (
            kind=:edge,
            cell=slice.cell,
            anchor=anchor,
            endpoints=(left, right),
            length=local_edge_length(sample.tree, left, right),
            rays=slice.flag_rays,
            tuple=local_flag_cell_tuple_tex(slice.flag_rays, flag_data, ray_lifts),
            cell_type=cell_type,
            location=string(slice.portion),
        ))
    end
    for wall in sample.walls
        vertex = wall.location.vertex
        cell_type = local_flag_type(:node, length(wall.rays))
        push!(items, (
            kind=:node,
            anchor=coordinates[vertex],
            vertex=vertex,
            rays=wall.rays,
            tuple=local_flag_cell_tuple_tex(wall.rays, flag_data, ray_lifts),
            cell_type=cell_type,
            location="node $vertex",
        ))
    end
    internal = Set(vertex for vertex in keys(sample.tree.adjacency)
                   if vertex > sample.tree.ntaxa)
    Set(item.vertex for item in items if item.kind == :node) == internal ||
        error("central node callouts do not cover every internal node")
    return items
end

local_node_certificate_key(orbit_number::Int, node) =
    (orbit_number, Tuple(sort!(collect(node.rays))))

local_certificate_ray_field(rays) = join(sort!(collect(rays)), ';')

function local_tetrahedral_intersection_witness(node, items)
    node.kind == :node && node.cell_type.name == "triangle" || return nothing
    tetrahedra = sort!([
        item
        for item in items
        if item.kind == :edge &&
           node.vertex in item.endpoints &&
           item.cell_type.name == "tetrahedron"
    ]; by=item -> Tuple(sort!(collect(item.rays))))
    length(tetrahedra) >= 2 || return nothing
    target = Set(node.rays)
    for left_index in 1:(length(tetrahedra) - 1)
        for right_index in (left_index + 1):length(tetrahedra)
            intersection = intersect(
                Set(tetrahedra[left_index].rays),
                Set(tetrahedra[right_index].rays),
            )
            intersection == target && return (
                left=tetrahedra[left_index],
                right=tetrahedra[right_index],
            )
        end
    end
    return nothing
end

function local_write_intersection_certificate(path, samples, flag_data, ray_lifts)
    rows = Any[]
    redundant_nodes = Set{Tuple}()
    for (orbit_number, sample) in enumerate(samples)
        coordinates = symmetric_layout(sample.tree; radius=LOCAL_CENTRAL_RADIUS)
        items = local_central_items(sample, coordinates, flag_data, ray_lifts)
        for node in items
            node.kind == :node && node.cell_type.name == "triangle" || continue
            witness = local_tetrahedral_intersection_witness(node, items)
            witness === nothing && continue
            key = local_node_certificate_key(orbit_number, node)
            push!(redundant_nodes, key)
            push!(rows, (
                orbit=orbit_number,
                node_rays=sort!(collect(node.rays)),
                left=witness.left,
                right=witness.right,
            ))
        end
    end
    length(redundant_nodes) == 146 || error(
        "expected 146 tetrahedral-facet intersections, found $(length(redundant_nodes))",
    )
    sort!(rows; by=row -> (row.orbit, Tuple(row.node_rays)))
    checked_at = Dates.format(Dates.now(), dateformat"yyyy-mm-ddTHH:MM:SS")
    open(path, "w") do io
        println(io, "# Exact local flag-polytope intersection certificate")
        println(io, "# checked_at=$checked_at")
        println(io, "# source=$(basename(CLEAN_ATLAS_FAN))")
        println(io, "# statement=Each listed node triangle is exactly the intersection of the vertex sets of the two listed adjacent tetrahedra.")
        println(io, "orbit\tnode_flag_rays\tedge_1_location\tedge_1_flag_rays\tedge_2_location\tedge_2_flag_rays")
        for row in rows
            println(
                io,
                join((
                    row.orbit,
                    local_certificate_ray_field(row.node_rays),
                    row.left.location,
                    local_certificate_ray_field(row.left.rays),
                    row.right.location,
                    local_certificate_ray_field(row.right.rays),
                ), '\t'),
            )
        end
    end
    println("wrote exact intersection certificate: $path ($checked_at)")
    return redundant_nodes
end

function local_load_intersection_certificate(path)
    lines = readlines(path)
    checked_at_lines = filter(line -> startswith(line, "# checked_at="), lines)
    length(checked_at_lines) == 1 || error(
        "intersection certificate has no unique check date: $path",
    )
    header_index = findfirst(line -> startswith(line, "orbit\t"), lines)
    header_index === nothing && error("intersection certificate has no table header: $path")
    redundant_nodes = Set{Tuple}()
    for line in lines[(header_index + 1):end]
        isempty(strip(line)) && continue
        fields = split(line, '\t'; keepempty=true)
        length(fields) == 6 || error("malformed intersection-certificate row: $line")
        orbit_number = parse(Int, fields[1])
        node_rays = Tuple(parse.(Int, split(fields[2], ';')))
        push!(redundant_nodes, (orbit_number, node_rays))
    end
    length(redundant_nodes) == 146 || error(
        "intersection certificate must contain 146 distinct node facets; " *
        "remove it to repeat the exact check",
    )
    checked_at = split(only(checked_at_lines), '='; limit=2)[2]
    println("using cached intersection certificate checked at $checked_at: $path")
    return redundant_nodes
end

function local_intersection_certificate(samples, flag_data, ray_lifts)
    return isfile(LOCAL_INTERSECTION_CERTIFICATE) ?
        local_load_intersection_certificate(LOCAL_INTERSECTION_CERTIFICATE) :
        local_write_intersection_certificate(
            LOCAL_INTERSECTION_CERTIFICATE,
            samples,
            flag_data,
            ray_lifts,
        )
end

"Omit each node triangle that is the intersection of two adjacent tetrahedra."
function local_visible_callout_items(items)
    return [item for item in items
            if local_tetrahedral_intersection_witness(item, items) === nothing]
end

function local_callout_sides(items)
    left = Any[]
    right = Any[]
    centre = Any[]
    for item in items
        if item.anchor[1] < 0
            push!(left, item)
        elseif item.anchor[1] > 0
            push!(right, item)
        else
            push!(centre, item)
        end
    end
    # Items exactly on the dividing axis have no intrinsic side; balance only
    # those items.  Once an item lies strictly left or right, never move it
    # across the tree merely to equalize column lengths.
    sort!(centre; by=item -> -item.anchor[2])
    for item in centre
        length(left) <= length(right) ? push!(left, item) : push!(right, item)
    end
    endpoint_order(item) = (-item.anchor[2], item.anchor[1], string(item.location))
    sort!(left; by=endpoint_order)
    sort!(right; by=endpoint_order)
    return left, right
end

"Summand lines of a callout: none unless the flag cell of an edge is prime."
local_summand_lines(item, summand_lines) =
    item.kind == :edge ? get(summand_lines, item.location, String[]) : String[]

local_callout_height(item, summand_lines) = LOCAL_CALLOUT_LINE_HEIGHT +
    length(local_summand_lines(item, summand_lines)) * LOCAL_CALLOUT_SUMMAND_HEIGHT

"""
Stack the boxes of one side with equal gaps.  The outer boxes are centred at
the ends of the callout span, so boxes of equal height are evenly spaced.
"""
function local_callout_rows(items, summand_lines; shift::Float64=0.0)
    isempty(items) && return Tuple{Any,Float64}[]
    length(items) == 1 && return [(only(items), shift)]
    heights = [local_callout_height(item, summand_lines) for item in items]
    top = LOCAL_CALLOUT_HALF_SPAN + shift + first(heights) / 2
    bottom = -LOCAL_CALLOUT_HALF_SPAN + shift - last(heights) / 2
    gap = (top - bottom - sum(heights)) / (length(items) - 1)
    rows = Tuple{Any,Float64}[]
    for (item, height) in zip(items, heights)
        push!(rows, (item, top - height / 2))
        top -= height + gap
    end
    return rows
end

function local_callout_style(item)
    if item.kind == :edge
        item.cell_type.name == "square pyramid" &&
            return ("pyramid callout", "pyramid leader")
        item.cell_type.name == "triangular prism" &&
            return ("prism callout", "prism leader")
        return ("edge callout", "edge leader")
    end
    return item.cell_type.exceptional ?
        ("square node callout", "square node leader") :
        ("node callout", "node leader")
end

function local_callout_geometry(item, side::Symbol, y::Float64, index::Int, summand_lines)
    box_style, leader_style = local_callout_style(item)
    box_x = side == :left ? -LOCAL_CALLOUT_X : LOCAL_CALLOUT_X
    anchor = side == :left ? "east" : "west"
    body = "\\($(item.cell_type.symbol)\\;$(item.tuple)\\)"
    for line in local_summand_lines(item, summand_lines)
        body *= "\\\\{\\fontsize{12}{14}\\selectfont\\color{toricgreen}\\($line\\)}"
    end
    return (
        item=item,
        side=side,
        y=y,
        index=index,
        box_style=box_style,
        leader_style=leader_style,
        box_x=box_x,
        anchor=anchor,
        body=body,
    )
end

function local_write_callout_leader(io, callout)
    ax, ay = callout.item.anchor
    println(
        io,
        @sprintf(
            "\\draw[%s] (%.5f,%.5f)--(%.5f,%.5f);",
            callout.leader_style, callout.box_x, callout.y, ax, ay,
        ),
    )
end


function local_write_callout_box(io, callout)
    println(
        io,
        @sprintf(
            "\\node[%s,anchor=%s] (callout-%d) at (%.5f,%.5f) {%s};",
            callout.box_style,
            callout.anchor,
            callout.index,
            callout.box_x,
            callout.y,
            callout.body,
        ),
    )
end

function local_write_central_tree(
    io,
    sample,
    flag_data,
    ray_lifts;
    summand_lines,
    callout_shift::Float64=0.0,
    centre=(0.0, 0.0),
)
    tree = sample.tree
    coordinates, names = local_prefixed_coordinates(
        tree, "central", centre, LOCAL_CENTRAL_RADIUS,
    )
    local_declare_coordinates(io, coordinates, names)
    items = local_central_items(sample, coordinates, flag_data, ray_lifts)
    edge_items = Dict(
        Tuple(sort(collect(item.endpoints))) => item
        for item in items if item.kind == :edge
    )
    square_nodes = Set(
        item.vertex for item in items if item.kind == :node && item.cell_type.exceptional
    )
    for (left, right, _) in flag_tree_edges(tree)
        pendant = left <= tree.ntaxa || right <= tree.ntaxa
        edge = Tuple(sort((left, right)))
        item = get(edge_items, edge, nothing)
        style = if item !== nothing && item.cell_type.name == "square pyramid"
            "central pyramid edge"
        elseif item !== nothing && item.cell_type.name == "triangular prism"
            "central prism edge"
        else
            pendant ? "central pendant edge" : "central internal edge"
        end
        println(io, "\\draw[$style] ($(names[left]))--($(names[right]));")
    end

    visible_items = local_visible_callout_items(items)
    left, right = local_callout_sides(visible_items)
    callouts = Any[]
    index = 0
    for (item, y) in local_callout_rows(left, summand_lines; shift=callout_shift)
        index += 1
        push!(callouts, local_callout_geometry(item, :left, y, index, summand_lines))
    end
    for (item, y) in local_callout_rows(right, summand_lines; shift=callout_shift)
        index += 1
        push!(callouts, local_callout_geometry(item, :right, y, index, summand_lines))
    end
    for callout in callouts
        local_write_callout_leader(io, callout)
    end

    for vertex in sort([vertex for vertex in keys(tree.adjacency) if vertex > tree.ntaxa])
        style = vertex in square_nodes ? "square node" : "internal vertex"
        println(io, "\\node[$style] at ($(names[vertex])) {};")
    end
    local_write_taxa(io, tree, names)
    for (left_vertex, right_vertex, edge_length) in flag_tree_edges(tree)
        println(
            io,
            "\\path ($(names[left_vertex]))--" *
            "node[central length,pos=.50] {\\($(tex_rational(edge_length))\\)}" *
            "($(names[right_vertex]));",
        )
    end
    for callout in callouts
        local_write_callout_box(io, callout)
    end
    return items
end

