###############################################################################
#
#  Local-cell atlas for the coarsest G2 flag fans over QQ and over GF(2).
#
#  Each maximal support-orbit representative of either field is drawn as a
#  local triangle or square; an orbit present over both fields is drawn once
#  and says so.  The exact minimal metric trees over its support rays
#  sit at the polygon vertices, while an exact generic maximal metric tree sits
#  in the middle.  Every edge and internal node of the central tree is joined
#  directly to its complete flag-ray vertex tuple in R_i^kappa notation; a
#  prime flag cell also names the two Minkowski summands of its
#  Newton--Okounkov polytope.  Page 3 draws, with polymake, the three- and
#  four-dimensional smallest pieces of these polytopes.  A final comparison
#  page draws one representative of the prevariety-only tetrahedron orbit in
#  the same ray-at-vertex convention.
#
#  Run from julia/ with
#
#    julia --project=. studies/g2/atlas/flag/build_local_flag_cell_atlas.jl
#
###############################################################################

