    Maximal-cell orbits & 31 & 32
  \end{tabular}\par\vspace{2mm}
  Both fans have dimension 6 and lineality dimension 3.\par\vspace{2mm}
  Lists: field-specific census ray indices. Underlining: pictured tree.
  Classes 1--11: QQ ray-orbit order.
