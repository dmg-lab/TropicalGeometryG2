#!/usr/bin/env julia

# Three-page atlas of the maintained QQ and GF(2) G2-Grassmannian fans.
# Run from the repository root with julia --project=julia <this file>.
using TOML
using Printf
using SHA

const FIELD_COMPARISON_ROOT = normpath(joinpath(@__DIR__, "../../../../.."))
const FIELD_COMPARISON_TEX = joinpath(@__DIR__, "field_comparison_atlas.tex")
const FIELD_COMPARISON_RAYS = joinpath(@__DIR__, "field_ray_classes.tex")
const FIELD_COMPARISON_METADATA = joinpath(@__DIR__, "field_comparison_assets", "atlas_data.toml")
const FIELD_COMPARISON_PDF = joinpath(FIELD_COMPARISON_ROOT, "output", "pdf", "g2_grassmannian_qq_gf2_orbit_atlas.pdf")
const FIELD_COMPARISON_BUILD = joinpath(FIELD_COMPARISON_ROOT, "julia", "work", "tex", "g2_grassmannian_qq_gf2_orbit_atlas")

function field_comparison_validate(data)
    @assert data["verified"]
    @assert length(data["rays"]) == 12
    @assert length(data["common"]) == 28
    @assert sum(row["size"] for row in data["common"]) == 236
    @assert sum(row["size"] for row in data["qq_only"]) == 12
    @assert sum(row["size"] for row in data["gf2_only"]) == 18
    @assert length(data["qq_only"]) == 3 && length(data["gf2_only"]) == 4
    @assert [row["class"] for row in data["rays"] if row["gf2_specific"]] == [12]
    @assert data["rays"][12]["gf2_members"] == [3, 36, 39]
    for (relative, digest) in data["input_sha256"]
        path = joinpath(FIELD_COMPARISON_ROOT, relative)
        bytes2hex(sha256(read(path))) == digest || error("Stale atlas assets: $relative. Regenerate with --force-assets.")
    end
    for collection in ("rays", "common", "qq_only", "gf2_only"), row in data[collection]
        isfile(joinpath(@__DIR__, "field_comparison_assets", row["tree_file"])) || error("Missing tree asset")
    end
    return data
end

function field_ray_member_tex(members, representative)
    isempty(members) && return raw"\text{absent}"
    return join([index == representative ? "\\underline{$index}" : string(index) for index in members], ",\\,")
end

function field_comparison_ray_page(data)
    open(FIELD_COMPARISON_RAYS, "w") do io
        print(io, raw"""% Generated by build_field_comparison_atlas.jl.
\begingroup
\setlength{\fboxsep}{1.0mm}
\setlength{\fboxrule}{.4pt}
\newcommand{\FieldRayCard}[7]{%
  \fcolorbox{#6}{white}{%
    \begin{minipage}[t][6.10cm][t]{9.40cm}
      \vspace{0pt}%
      \colorbox{#6!12}{\parbox{\dimexpr\linewidth-2\fboxsep\relax}{%
        \fontsize{12}{13}\selectfont\bfseries $\mathsf{R}_{#1}$%
        \hfill\normalfont\fontsize{10}{11}\selectfont #2\quad #5}}
      \par\vspace{.6mm}
      {\centering\fontsize{9.5}{11}\selectfont
        $\mathbb{Q}:\ #3$\par $\mathbb{F}_{2}:\ #4$\par}
      \begin{minipage}[c][4.82cm][c]{\linewidth}\centering
        \resizebox{4.70cm}{!}{\input{#7}}%
      \end{minipage}
    \end{minipage}%
  }%
}
\newcommand{\FieldKeyCard}[2]{%
  \fcolorbox{cellline!50}{paperblue!22}{%
