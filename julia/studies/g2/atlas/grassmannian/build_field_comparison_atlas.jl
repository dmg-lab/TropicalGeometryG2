  Its three GF(2) rays, $3,36,39$, are the centers of the three
  Dressian tetrahedra. No QQ ray belongs to this class.\par\vspace{2mm}
  In each tetrahedron, the four QQ boundary triangles are replaced by the
  six GF(2) triangles joining the center to the six edges.\par\vspace{2mm}
  Under the full Weyl group, these give three QQ-only maximal-cell orbits
  and four GF(2)-only maximal-cell orbits. The detailed colored comparison
  is on page 3.
