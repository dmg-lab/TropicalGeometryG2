function field_comparison_compile()
    pdflatex = Sys.which("pdflatex")
    pdflatex === nothing && error("pdflatex is required")
    mkpath(FIELD_COMPARISON_BUILD)
    mkpath(dirname(FIELD_COMPARISON_PDF))
    command = Cmd(Cmd([pdflatex, "-interaction=nonstopmode", "-halt-on-error", "-file-line-error",
        "-output-directory=$FIELD_COMPARISON_BUILD", basename(FIELD_COMPARISON_TEX)]); dir=@__DIR__)
    run(command)
    run(command)
    compiled = joinpath(FIELD_COMPARISON_BUILD, "field_comparison_atlas.pdf")
    isfile(compiled) || error("LaTeX did not produce the atlas")
    cp(compiled, FIELD_COMPARISON_PDF; force=true)
    return FIELD_COMPARISON_PDF
end

function build_field_comparison_atlas(; compile_pdf=true, reuse_assets=false, force_assets=false)
    if !reuse_assets || !isfile(FIELD_COMPARISON_METADATA)
        include(joinpath(@__DIR__, "export_field_atlas_assets.jl"))
        Base.invokelatest(G2FieldAtlasAssets.build_field_atlas_assets; force=force_assets)
    end
    data = field_comparison_validate(TOML.parsefile(FIELD_COMPARISON_METADATA))
    field_comparison_ray_page(data)
    field_comparison_document()
    for fragment in ("field_common_cells.tex", "field_tetrahedron_comparison.tex")
        isfile(joinpath(@__DIR__, fragment)) || error("Missing atlas page: $fragment")
    end
    println("TeX: ", FIELD_COMPARISON_TEX)
    pdf = compile_pdf ? field_comparison_compile() : nothing
    pdf === nothing || println("PDF: ", pdf)
    return (; tex=FIELD_COMPARISON_TEX, pdf, data)
end

if abspath(PROGRAM_FILE) == @__FILE__
    build_field_comparison_atlas(; compile_pdf=!("--no-pdf" in ARGS),
        reuse_assets="--reuse-assets" in ARGS, force_assets="--force-assets" in ARGS)
end
