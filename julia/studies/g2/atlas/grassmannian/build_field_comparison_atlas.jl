\FieldKeyCard{Fields and fan sizes}{%
  \begin{tabular}{@{}lrr@{}}
    & $\mathbb{Q}$ & $\mathbb{F}_{2}$\\[2mm]
    Rays & 51 & 54\\
    Ray orbits & 11 & 12\\[1mm]
