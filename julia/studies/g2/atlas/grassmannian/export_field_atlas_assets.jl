#!/usr/bin/env julia

# Exact, input-ready assets for the QQ / GF(2) Grassmannian orbit atlas.
# The shared tree renderer is used only for drawing. All indices, incidences and
# normalized cell trees come from the maintained field-specific census.
module G2FieldAtlasAssets

const FIELD_TREE_RENDERER = normpath(joinpath(
    @__DIR__, "..", "..", "..", "..", "to_tex", "render_maximal_cell_tree.jl",
))
include(FIELD_TREE_RENDERER)

using TOML
using SHA

export build_field_atlas_assets

const FIELD_ASSET_DIR = joinpath(@__DIR__, "field_comparison_assets")
const FIELD_ATLAS_DATA = joinpath(FIELD_ASSET_DIR, "atlas_data.toml")

field_row(matrix, index) = QQ.(collect(matrix[index, :]))
field_rational(value) = denominator(QQ(value)) == 1 ? string(numerator(QQ(value))) :
    "$(numerator(QQ(value)))/$(denominator(QQ(value)))"

function field_load_source(target)
    directory = TropicalCensus.data_path("g2", target)
    fan = load(joinpath(directory, "03_normalized_coarsest_fan.mrdi"))
    rays = Matrix{QQFieldElem}(load(joinpath(directory, "03_normalized_rays.mrdi")))
    weights = Matrix{QQFieldElem}(load(joinpath(directory, "04_canonical_cell_weights.mrdi")))
    incidence = Matrix{Bool}(maximal_cones(IncidenceMatrix, fan))
    cells = [findall(identity, collect(row)) for row in eachrow(incidence)]
    actions = Matrix{ZZRingElem}(load(joinpath(directory, "05_symmetry_ray_actions.mrdi")))
    ray_orbits = TropicalCensus.action_orbits([Int.(collect(row)) for row in eachrow(actions)], size(rays, 1))
    cell_orbits = Dict{Int,Dict{String,Any}}()
    for line in readlines(joinpath(directory, "05_symmetry_cell_orbits.csv"))[2:end]
        fields = split(line, ','; limit=4)
        members = parse.(Int, split(strip(fields[4], '"'), ';'))
        cell_orbits[parse(Int, fields[1])] = Dict(
            "size" => parse(Int, fields[2]), "representative" => parse(Int, fields[3]),
            "members" => members,
        )
    end
    cell_trees = Matrix{QQFieldElem}(load(joinpath(directory, "04_normalized_cell_trees.mrdi")))
    @assert size(weights) == size(cell_trees) == (length(cells), 21)
    for (index, cell) in enumerate(cells)
        @assert field_row(weights, index) == vec(sum(rays[cell, :]; dims=1))
        @assert field_row(cell_trees, index) == balance_outer_edges(field_row(weights, index)).balanced_generator
    end
    return (; directory, fan, rays, weights, cell_trees, cells, ray_orbits, cell_orbits)
end

"""Decorate the shared renderer in the local flag atlas's visual convention."""
function field_tree_fragment(tree; letters=false, metrics=true, weight_font=9.25)
    fragment = g2_tree_tikz(tree; palette=:color, label=true,
        bounded_length=letters ? 1.0 : G2_TREE_BOUNDED_DRAW_LENGTH,
        edge_labels=metrics ? :disk : :none)
    fragment = replace(fragment,
        "g2tree pendant/.style={draw=g2EdgeBlue" => "g2tree pendant/.style={draw=black!43",
        "minimum size=8.5pt" => "minimum size=10.0pt",
        "\\fontsize{7.5}{8}" => "\\fontsize{$weight_font}{$(weight_font + 0.5)}",
    )
    if letters
        letter_style = "g2tree lettered vertex/.style={circle,fill=g2EdgeBlue," *
            "draw=white,line width=.7pt,inner sep=0pt,minimum size=5.0mm," *
            "font={\\sffamily\\fontsize{10}{10}\\selectfont\\bfseries},text=white},\n"
        fragment = replace(fragment, "\\tikzset{\n" => "\\tikzset{\n" * letter_style)
        internal = sort!([vertex for vertex in keys(tree.adjacency) if vertex > tree.ntaxa])
        for (index, vertex) in enumerate(internal)
            letter = string(Char(Int('A') + index - 1))
            fragment = replace(fragment,
                "\\node[g2tree vertex] at (v$vertex) {};" =>
                "\\node[g2tree lettered vertex] at (v$vertex) {$letter};")
        end
    end
    return fragment
end

function field_write_fragment(relative, tree; kwargs...)
    path = joinpath(FIELD_ASSET_DIR, relative)
    mkpath(dirname(path))
    write(path, "% Generated by export_field_atlas_assets.jl from the maintained census.\n" *
        field_tree_fragment(tree; kwargs...))
    return relative
end

function field_tree_metadata(tree, weight)
    splits = internal_splits(tree)
    internal = sort!([vertex for vertex in keys(tree.adjacency) if vertex > tree.ntaxa])
    return Dict{String,Any}(
        "weight" => field_rational.(weight),
        "pendant_lengths" => field_rational.(pendant_lengths(tree)),
        "internal_splits" => [join(split.side, ",") * "|" * join(split.complement, ",") *
            ":" * field_rational(split.length) for split in splits],
        "internal_vertices" => internal,
        "internal_letters" => [string(Char(Int('A') + index - 1)) for index in eachindex(internal)],
    )
end

function field_polygon_order(cell, rays, quotient)
    length(cell) == 3 && return sort(cell)
    length(cell) == 4 || error("unexpected maximal cell size")
    relation = Matrix{QQFieldElem}(kernel(matrix(QQ, transpose(rays[cell, :] * quotient)); side=:right))
    # Oscar returns a right-kernel basis as column vectors.
    size(relation) == (4, 1) || error("square has wrong relation space: $(size(relation))")
    positive = cell[findall(>(0), vec(relation))]
    negative = cell[findall(<(0), vec(relation))]
    length(positive) == length(negative) == 2 || error("square relation does not alternate")
    sort!(positive); sort!(negative)
    return [positive[1], negative[1], positive[2], negative[2]]
end

function build_field_atlas_assets(; force=false)
    if !force && isfile(FIELD_ATLAS_DATA)
        result = TOML.parsefile(FIELD_ATLAS_DATA)
        repository = TropicalCensus.project_path("..")
        inputs_match = haskey(result, "input_sha256") && all(
            isfile(joinpath(repository, path)) &&
                bytes2hex(sha256(read(joinpath(repository, path)))) == digest
            for (path, digest) in result["input_sha256"]
        )
        code_matches = get(result, "exporter_sha256", "") == bytes2hex(sha256(read(@__FILE__))) &&
            get(result, "renderer_sha256", "") == bytes2hex(sha256(read(FIELD_TREE_RENDERER)))
        inputs_match && code_matches &&
        all(isfile(joinpath(FIELD_ASSET_DIR, record["tree_file"])) for collection in
            ("rays", "common", "qq_only", "gf2_only") for record in result[collection]) &&
        all(isfile(joinpath(FIELD_ASSET_DIR, relative)) for relative in (
            "tetra/qq_ray_06.tex", "tetra/qq_ray_09.tex", "tetra/qq_ray_34.tex", "tetra/qq_ray_40.tex",
            "tetra/gf2_ray_03.tex", "exceptional/gf2_central_ray.tex")) &&
            return merge(result, Dict("metadata_path" => FIELD_ATLAS_DATA))
    end
    qq = field_load_source("grassmannian")
    gf2 = field_load_source("grassmannian_gf2")
    comparison_path = joinpath(gf2.directory, "09_qq_comparison.json")
    comparison = Oscar.JSON.parsefile(comparison_path)
    @assert comparison["verified"]
    @assert (size(qq.rays, 1), length(qq.cells), length(qq.ray_orbits), length(qq.cell_orbits)) == (51, 248, 11, 31)
    @assert (size(gf2.rays, 1), length(gf2.cells), length(gf2.ray_orbits), length(gf2.cell_orbits)) == (54, 254, 12, 32)

    quotient = Matrix{QQFieldElem}(kernel(matrix(QQ, balanced_lineality_basis()); side=:right))
    qkeys = [TropicalCensus.quotient_ray_signature(row, quotient) for row in eachrow(qq.rays)]
    fkeys = [TropicalCensus.quotient_ray_signature(row, quotient) for row in eachrow(gf2.rays)]
    flut = Dict(key => index for (index, key) in enumerate(fkeys))
    ray_map = [flut[key] for key in qkeys]
    @assert ray_map == [Int(comparison["qq_to_gf2_ray_indices"][string(index)]) for index in 1:51]
    @assert sort!(setdiff(collect(1:54), ray_map)) == Int.(comparison["new_gf2_ray_orbit"])
    qq_class = Dict(ray => orbit for (orbit, members) in enumerate(qq.ray_orbits) for ray in members)
    gf2_class = Dict(ray_map[ray] => qq_class[ray] for ray in 1:51)
    for ray in comparison["new_gf2_ray_orbit"]
        gf2_class[Int(ray)] = 12
    end
    f_orbit_of = Dict(ray => orbit for (orbit, members) in enumerate(gf2.ray_orbits) for ray in members)

    metadata = Dict{String,Any}(
        "format_version" => 1,
        "symmetry_group_order" => 12,
        "indexing" => "Current stage-3 normalized census fans; ray classes R1..R11 are QQ stage-5 symmetry orbit order; R12 is GF(2)-specific.",
        "common_maximal_cells" => 236, "common_maximal_cell_orbits" => 28,
        "ray_classes" => 12,
        "qq_rays" => 51, "gf2_rays" => 54,
        "qq_maximal_cells" => 248, "gf2_maximal_cells" => 254,
        "qq_maximal_cell_orbits" => 31, "gf2_maximal_cell_orbits" => 32,
        "cell_tree_metric" => "Stage-4 normalized cell tree: the equal positive sum of the normalized rays, normalized as the rays are.",
        "ray_tree_metric" => "Primitive integral Coxeter-balanced tree metric, minimum pendant edge zero.",
        "taxon_key" => "1 blue square; 2 blue triangle; 3 blue circle; 4 yellow square; 5 yellow triangle; 6 yellow circle; 7 red heart.",
        "qq_to_gf2_ray_indices" => ray_map,
        "rays" => Dict{String,Any}[], "common" => Dict{String,Any}[],
        "qq_only" => Dict{String,Any}[], "gf2_only" => Dict{String,Any}[],
    )

    for class in 1:12
        specific = class == 12
        qmembers = specific ? Int[] : qq.ray_orbits[class]
        fmembers = specific ? Int.(comparison["new_gf2_ray_orbit"]) : sort(ray_map[qmembers])
        representative = specific ? first(fmembers) : first(qmembers)
        raw = field_row(specific ? gf2.rays : qq.rays, representative)
        balanced = balance_outer_edges(raw)
        tree_file = field_write_fragment(@sprintf("rays/ray_%02d.tex", class), balanced.tree;
            letters=true, weight_font=10.25)
        record = merge(field_tree_metadata(balanced.tree, balanced.balanced_generator), Dict{String,Any}(
            "class" => class, "label" => "R$class", "size" => length(fmembers),
            "gf2_specific" => specific, "qq_orbit" => specific ? 0 : class,
            "gf2_orbit" => f_orbit_of[first(fmembers)],
            "qq_representative" => specific ? 0 : representative,
            "gf2_representative" => specific ? representative : ray_map[representative],
            "qq_members" => qmembers, "gf2_members" => fmembers, "tree_file" => tree_file,
        ))
        @assert Set(fmembers) == Set(gf2.ray_orbits[record["gf2_orbit"]])
        push!(metadata["rays"], record)
    end

    gf2_cell_lut = Dict(Tuple(sort(cell)) => index for (index, cell) in enumerate(gf2.cells))
    for (index, correspondence) in enumerate(comparison["common_orbit_correspondence"])
        qo = Int(correspondence["qq_orbit"]); fo = Int(correspondence["gf2_orbit"])
        qrecord = qq.cell_orbits[qo]; frecord = gf2.cell_orbits[fo]
        qrep = qrecord["representative"]; qrays = qq.cells[qrep]
        frays = ray_map[qrays]; frep = gf2_cell_lut[Tuple(sort(frays))]
        @assert frep in frecord["members"]
        @assert qrecord["size"] == frecord["size"] == Int(correspondence["size"])
        @assert Set(gf2_cell_lut[Tuple(sort(ray_map[qq.cells[cell]]))] for cell in qrecord["members"]) == Set(frecord["members"])
        weight = field_row(qq.cell_trees, qrep)
        tree = tree_from_min_pluecker(weight)
        ordered = field_polygon_order(qrays, qq.rays, quotient)
        classes = [qq_class[ray] for ray in ordered]
        record = merge(field_tree_metadata(tree, weight), Dict{String,Any}(
            "index" => index, "qq_orbit" => qo, "gf2_orbit" => fo,
            "size" => qrecord["size"], "qq_representative" => qrep,
            "gf2_representative" => frep,
            "gf2_orbit_census_representative" => frecord["representative"],
            "qq_members" => qrecord["members"], "gf2_members" => frecord["members"],
            "qq_rays" => qrays, "gf2_rays" => frays,
            "ordered_qq_rays" => ordered, "ordered_gf2_rays" => ray_map[ordered],
            "ray_classes" => classes, "ray_class_multiset" => sort(classes),
            "shape" => length(qrays) == 3 ? "triangle" : "quadrilateral",
            "tree_file" => field_write_fragment(@sprintf("common/common_%02d.tex", index), tree),
        ))
        push!(metadata["common"], record)
    end
    @assert length(metadata["common"]) == 28
    @assert sum(record["size"] for record in metadata["common"]) == 236
    @assert count(record -> record["shape"] == "quadrilateral", metadata["common"]) == 1

    for (key, source, classes) in (("qq_only", qq, qq_class), ("gf2_only", gf2, gf2_class))
        prefix = key == "qq_only" ? "qq" : "gf2"
        for exceptional in comparison[key * "_orbits"]
            orbit = Int(exceptional["orbit"]); census = source.cell_orbits[orbit]
            rep = census["representative"]; rays = source.cells[rep]
            @assert rays == Int.(exceptional["representative_rays"])
            tree = tree_from_min_pluecker(field_row(source.cell_trees, rep))
            record = merge(field_tree_metadata(tree, field_row(source.cell_trees, rep)), Dict{String,Any}(
                "orbit" => orbit, "size" => census["size"], "representative" => rep,
                "members" => census["members"], "rays" => rays,
                "ray_classes" => [classes[ray] for ray in rays], "shape" => "triangle",
                "tree_file" => field_write_fragment(@sprintf("exceptional/%s_%02d.tex", prefix, orbit), tree),
            ))
            push!(metadata[key], record)
        end
    end

    metadata["tetrahedra"] = Dict{String,Any}[]
    inverse_map = Dict(value => index for (index, value) in enumerate(ray_map))
    for tetra in comparison["tetrahedra"]
        central = Int(tetra["central_ray_gf2"])
        vertices = Int.(tetra["vertex_rays_gf2"])
        push!(metadata["tetrahedra"], Dict{String,Any}(
            "dressian_cell" => Int(tetra["dressian_tetrahedron"]),
            "central_gf2_ray" => central, "central_ray_class" => 12,
            "qq_vertex_rays" => [inverse_map[ray] for ray in vertices],
            "gf2_vertex_rays" => vertices, "vertex_ray_classes" => [gf2_class[ray] for ray in vertices],
            "qq_boundary_cells" => Int.(tetra["qq_boundary_cells"]),
            "gf2_triangles" => Int.(tetra["gf2_triangles"]),
            "central_coefficients_in_primitive_vertex_rays" => Int.(tetra["central_coefficients_in_primitive_vertex_rays"]),
        ))
    end
    for ray in (6, 9, 34, 40)
        tree = balance_outer_edges(field_row(qq.rays, ray)).tree
        field_write_fragment(@sprintf("tetra/qq_ray_%02d.tex", ray), tree; letters=true, weight_font=10.25)
    end
    field_write_fragment("tetra/gf2_ray_03.tex", balance_outer_edges(field_row(gf2.rays, 3)).tree;
        letters=true, weight_font=10.25)
    field_write_fragment("exceptional/gf2_central_ray.tex", balance_outer_edges(field_row(gf2.rays, 3)).tree;
        letters=true, weight_font=10.25)

    provenance = Dict{String,String}()
    for source in (qq, gf2), name in (
        "03_normalized_coarsest_fan.mrdi", "03_normalized_rays.mrdi", "04_canonical_cell_weights.mrdi",
        "04_normalized_cell_trees.mrdi", "05_symmetry_ray_actions.mrdi", "05_symmetry_cell_orbits.csv")
        path = joinpath(source.directory, name)
        provenance[relpath(path, TropicalCensus.project_path(".."))] = bytes2hex(sha256(read(path)))
    end
    provenance[relpath(comparison_path, TropicalCensus.project_path(".."))] = bytes2hex(sha256(read(comparison_path)))
    metadata["input_sha256"] = provenance
    metadata["exporter_sha256"] = bytes2hex(sha256(read(@__FILE__)))
    metadata["renderer_sha256"] = bytes2hex(sha256(read(FIELD_TREE_RENDERER)))
    metadata["verified"] = true
    mkpath(FIELD_ASSET_DIR)
    open(FIELD_ATLAS_DATA, "w") do io
        TOML.print(io, metadata; sorted=true)
    end
    println("Exported twelve exact ray classes, 28 common orbits, seven exceptional orbit trees.")
    println("Metadata: ", FIELD_ATLAS_DATA)
    return merge(metadata, Dict("metadata_path" => FIELD_ATLAS_DATA))
end

end # module G2FieldAtlasAssets

if abspath(PROGRAM_FILE) == @__FILE__
    G2FieldAtlasAssets.build_field_atlas_assets(; force="--force" in ARGS)
end
