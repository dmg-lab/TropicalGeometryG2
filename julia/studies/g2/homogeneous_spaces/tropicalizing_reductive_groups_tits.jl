#=
The Tits lifts of Section 8 of main.tex (Remark on Tits lifts).

The signed permutation matrices in G2 (in the coordinates of main.tex) lying over the Weyl group D12: they form
N(T)(ZZ), of order 48, and it contains complements isomorphic to D12. A signed permutation matrix g, with
g e_i = s_i e_{π(i)}, lies in G2 when it fixes Φ = e123 + e456 + e147 + e257 + e367 and has determinant 1.

Usage, from julia/ (a few seconds):
    julia --project=. studies/g2/homogeneous_spaces/tropicalizing_reductive_groups_tits.jl \
        > studies/g2/homogeneous_spaces/tropicalizing_reductive_groups_tits.txt
=#

using LinearAlgebra

const PHI = Dict((1, 2, 3) => 1, (4, 5, 6) => 1, (1, 4, 7) => 1, (2, 5, 7) => 1, (3, 6, 7) => 1)

"The image of Φ under g e_i = signs[i] e_{perm[i]}, as a dictionary of its nonzero coefficients."
function act(perm, signs)
    image = Dict{NTuple{3,Int},Int}()
    for ((a, b, c), v) in PHI
        index = (perm[a], perm[b], perm[c])
        order = sortperm(collect(index))
        inversions = count(i < j && order[i] > order[j] for i in 1:3 for j in 1:3)
        key = Tuple(sort(collect(index)))
        image[key] = get(image, key, 0) + v * signs[a] * signs[b] * signs[c] * (isodd(inversions) ? -1 : 1)
    end
    return filter(entry -> last(entry) != 0, image)
end

function signed_permutation_matrix(perm, signs)
    M = zeros(Int, 7, 7)
    foreach(i -> M[perm[i], i] = signs[i], 1:7)
    return M
end

"The lifts of `perm` to G2: the signed permutation matrices over it that fix Φ and have determinant 1."
function lifts(perm)
    matrices = Matrix{Int}[]
    for signs in Iterators.product(ntuple(_ -> (1, -1), 7)...)
        act(perm, signs) == PHI || continue
        M = signed_permutation_matrix(perm, signs)
        round(Int, det(M)) == 1 && push!(matrices, M)
    end
    return matrices
end

"The permutation of 1:7 of the cycle `c`."
function cycle(c)
    perm = collect(1:7)
    foreach(k -> perm[c[k]] = c[mod1(k + 1, length(c))], eachindex(c))
    return perm
end

order_of(A) = findfirst(k -> A^k == I, 1:24)

rotation = cycle([1, 5, 3, 4, 2, 6])                 # (1 5 3 4 2 6)
reflection = [1, 3, 2, 4, 6, 5, 7]                    # (2 3)(5 6)
R, S = lifts(rotation), lifts(reflection)
println("lifts of rotation ", length(R), "  lifts of reflection ", length(S))
D = lifts(collect(1:7))
println("signed diagonal elements in G2: ", length(D))

# The group generated by all lifts.
identity_matrix = Matrix{Int}(I, 7, 7)
group = Set([identity_matrix])
frontier = [identity_matrix]
while !isempty(frontier)
    global frontier
    new = Matrix{Int}[]
    for g in frontier, h in vcat(R, S)
        x = h * g
        x in group || (push!(group, x); push!(new, x))
    end
    frontier = new
end
println("order of the group of signed permutation matrices generated: ", length(group))

split = [(a, b) for a in R for b in S if a^6 == I && b * b == I && (b * a) * (b * a) == I]
println("pairs (rotation lift, reflection lift) generating a copy of D12: ", length(split))
println("orders of rotation lifts: ", sort(unique(order_of.(R))))
println("orders of reflection lifts: ", sort(unique(order_of.(S))))
