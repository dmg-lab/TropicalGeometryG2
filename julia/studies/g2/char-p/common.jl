# Shared code for the characteristic-p certificates of the tropical G2-Grassmannian
# (Theorem thm:charp in main.tex).  See README.md.
#
# Conventions.  All stored fans and weights are in the MIN convention (as in
# julia/data/g2); main.tex uses the MAX convention, so a weight w here is -w there.
# The weight order for a weight w is weight_ordering(c .- w, degrevlex) with
# c = maximum(w) + 1: it compares the w-weight first (smaller w-weight = larger term),
# then breaks ties by degrevlex.  For the homogeneous ideals at hand this is the order
# "refine -w (max convention) by degrevlex" of main.tex.
using Oscar

const DATA = joinpath(@__DIR__, "..", "..", "..", "data", "g2", "grassmannian")
const CERT = joinpath(@__DIR__, "certificates")
const PAIRS = [(i, j) for i in 1:6 for j in (i + 1):7]          # p12, ..., p67
const IDX = Dict(p => k for (k, p) in enumerate(PAIRS))

"The ideal I over ZZ: the 42 generators of julia/data/g2/grassmannian/00_ideal.mrdi (coefficients +-1)."
function ideal_ZZ()
  IQ = load(joinpath(DATA, "00_ideal.mrdi"))
  RQ = base_ring(IQ)
  @assert string.(symbols(RQ)) == ["p$i$j" for (i, j) in PAIRS]
  R, _ = polynomial_ring(ZZ, string.(symbols(RQ)))
  gens_Z = [map_coefficients(c -> (@assert isone(denominator(c)); ZZ(numerator(c))), g; parent = R) for g in gens(IQ)]
  return R, gens_Z
end

raw_fan() = load(joinpath(DATA, "01_raw_fan.mrdi"))

"Primitive integral rays (modulo lineality) of a cone."
function primitive_rays(C)
  out = Vector{Int}[]
  for r in rays_modulo_lineality(C).rays_modulo_lineality
    q = Vector{QQFieldElem}(r); d = lcm([denominator(a) for a in q]); z = [numerator(a * d) for a in q]
    g = gcd(z); push!(out, [Int(a ÷ g) for a in z])
  end
  out
end

"Interior point of a cone: the sum of its primitive rays (small entries; huge weights crash Singular)."
interior_point(C) = sum(primitive_rays(C))

lineality_generators(C) = [Vector{QQFieldElem}(l) for l in eachrow(Matrix{QQFieldElem}(generator_matrix(lineality_space(C))))]

weight_order(R, w) = weight_ordering((maximum(w) + 1) .- w, degrevlex(R))

"Initial form (MIN convention): the terms of minimal w-weight."
function initial_form(f, w)
  es = collect(exponents(f)); cs = collect(coefficients(f)); x = gens(parent(f))
  ws = [sum(e .* w) for e in es]; m = minimum(ws)
  sum(cs[i] * prod(x .^ es[i]) for i in eachindex(es) if ws[i] == m)
end

"""
    check_standard_representations(G, o)

For all pairs g1, g2 in G whose leading monomials are not coprime, form the S-polynomial
over ZZ,  S = (a/a1)(m/m1) g1 - (a/a2)(m/m2) g2  with a = lcm(lc), m = lcm(lm),  divide it
by G (reduce_with_quotients) and CHECK exactly in Julia that
  (i)  S = sum_g q_g g  (polynomial identity, remainder 0), and
  (ii) lm(q_g) lm(g) < m in the order o for every nonzero q_g.
This is the lcm-representation criterion used in the proof of Lemma lem:groebnerZ; pairs
with coprime leading monomials are covered by the product criterion over the field.
Returns (number of pairs checked, number of failures).
"""
function check_standard_representations(G, o)
  lms = [leading_monomial(g; ordering = o) for g in G]
  lcs = [leading_coefficient(g; ordering = o) for g in G]
  checked = 0; failures = 0
  for i in eachindex(G), j in (i + 1):length(G)
    m = lcm(lms[i], lms[j])
    m == lms[i] * lms[j] && continue                    # product criterion
    a = lcm(lcs[i], lcs[j])
    S = divexact(a, lcs[i]) * divexact(m, lms[i]) * G[i] - divexact(a, lcs[j]) * divexact(m, lms[j]) * G[j]
    checked += 1
    iszero(S) && continue
    q, r = reduce_with_quotients(S, G; ordering = o)
    ok = iszero(r) && sum(q[1, k] * G[k] for k in eachindex(G)) == S
    ok &= all(k -> iszero(q[1, k]) || cmp(o, leading_monomial(q[1, k]; ordering = o) * lms[k], m) < 0, eachindex(G))
    ok || (failures += 1)
  end
  return checked, failures
end

"Check that every generator f lies in the ZZ-ideal generated by G: division by G with exact identity."
function check_in_span(fs, G, o)
  all(fs) do f
    q, r = reduce_with_quotients(f, G; ordering = o)
    iszero(r) && sum(q[1, k] * G[k] for k in eachindex(G)) == f
  end
end

"Check stored cofactors: each g == sum_j cof[j] * gens[j]."
check_cofactors(G, cof, gens_Z) = all(k -> sum(cof[k][j] * gens_Z[j] for j in eachindex(gens_Z)) == G[k], eachindex(G))

