###############################################################################
#
#   Is the Chevalley cone a PRIME cone?
#
#   Kaveh-Manon: a finite Khovanskii basis for (R, nu) is the same data as a
#   maximal-dimensional PRIME cone of Trop(R), and the initial degeneration
#   along that cone is the toric variety of the Newton-Okounkov polytope.
#   The Chevalley point of X_{G_2} lies in the relative interior of one
#   maximal cone of trop(G) (Orbit 23).  This script verifies
#   the Kaveh-Manon prediction for that cone:
#
#     (1) in_w(I) is PRIME                          <- the prime-cone condition
#     (2) in_w(I) is generated by binomials
#     (3) dim in_w(I) = dim I                       <- the degeneration is flat
#     (4) deg in_w(I) = deg I = 18 = normalised volume of P_(1,3,2,3,1)
#     (5) every binomial is homogeneous for the grading p_ij |-> (1, nu(p_ij)),
#         which identifies in_w(I) as the toric ideal of the 14 lattice points
#         of the lecture-hall simplex.
#
#   Everything is in the split setting and the min convention, matching
#   ../main.tex and data/g2/grassmannian/00_ideal.mrdi (read only).
#
#   Run from julia/ with:  julia --project=. studies/g2/supplemental/g2_prime_cone.jl
#
###############################################################################

using TropicalGeometryG2
using Oscar
include(joinpath(@__DIR__, "g2_chevalley_valuation.jl"))
const DATA = data_path("g2", "grassmannian")

# --- the Chevalley valuation, in ../main.tex's Pluecker labels -------------
# Relabelled through SIGMA (g2_chevalley_valuation.jl), so that every index
# printed by this script is ../main.tex's.
r = [2,1,2,1,2]
_, nu = chevalley_valuations(W, [0, 1], r)
num = Dict(relabel(prs[t]) => nu[t] for t in 1:21)
w = [lam(num[p], 8, 30_000) for p in prs]; w = w .- minimum(w)

# --- the initial ideal -----------------------------------------------------
I = load(joinpath(DATA, "00_ideal.mrdi"))
println("ideal of the split G_2-Grassmannian: ", ngens(I), " generators, dim ", dim(I),
        ", degree ", degree(I))
nu_triv = tropical_semiring_map(QQ, min)
inI = initial(I, nu_triv, w)
G = gens(groebner_basis(inI; complete_reduction=true))
nterms = [length(terms(g)) for g in G]
println("\nin_w(I): ", length(G), " reduced Groebner basis elements")
println("(2) all binomial            : ", all(<=(2), nterms))
println("(3) dim in_w(I) = ", dim(inI), "  = dim I : ", dim(inI) == dim(I))
println("(4) deg in_w(I) = ", degree(inI), "  = deg I : ", degree(inI) == degree(I))
println("(1) IS PRIME                : ", is_prime(inI))

# --- and it is the toric variety of the lecture-hall simplex ---------------
A = [vcat(1, num[prs[t]]) for t in 1:21]
allhom = all(G) do g
    ds = [Adeg(m, A) for m in monomials(g)]
    all(==(ds[1]), ds)
end
P = chevalley_polytope(chevalley_data(:G, 2, [0,1]; word = r))
println("(5) every binomial is homogeneous for p_ij -> (1, nu(p_ij)): ", allhom)
println("    rank of that grading matrix = ",
        rank(matrix(QQ, reduce(hcat, [QQ.(c) for c in A]))), " (= dim of the affine cone)")
println("    normalised volume of P_(1,3,2,3,1) = ", normalised_volume_of(P))

# --- primality is a property of the CONE, not of the chosen point ----------
# in_w(I) is constant on the relative interior of a maximal cone of the
# Groebner fan structure.  We confirm that directly: three points coming from
# different order-preserving lambda, plus one built from the cone's own rays
# and so independent of the valuation altogether.
DATAF = load(joinpath(DATA, "01_raw_fan.mrdi"))
C = collect(maximal_cones(DATAF))[139]
raysum = sum([primitive_integer(Vector{QQFieldElem}(rr))
              for rr in rays_modulo_lineality(C)[:rays_modulo_lineality]])
mkw(B, K) = (u = [lam(num[q], B, K) for q in prs]; QQ.(u .- minimum(u)))
pts = ["lambda B=8" => mkw(8,30_000), "lambda B=10" => mkw(10,50_000),
       "lambda B=12" => mkw(12,100_000), "sum of the cone's rays" => raysum]
println("\n--- the same initial ideal at four points of the relative interior ---")
Js = Any[]
for (k, wv) in pts
    J = initial(I, nu_triv, Vector{QQFieldElem}(wv)); push!(Js, J)
    mono = any(g -> length(terms(g)) == 1, gens(groebner_basis(J; complete_reduction=true)))
    println("   ", rpad(k, 24), " in cone ", wv in C, ", prime ", is_prime(J),
            ", monomial-free ", !mono, ", dim ", dim(J), ", deg ", degree(J))
end
println("   all four initial ideals are equal: ", all(J -> J == Js[1], Js))

println("\nCONCLUSION: cone 139 is a PRIME CONE, and in_w(I) is the toric ideal of the ",
        length(lattice_points(P)), " lattice points of the lecture-hall simplex.")
