###############################################################################
# The table of the three cubics of the tropical basis of the G2-Grassmannian:
# two rows for each cubic, its five monomials and, under each monomial, the
# simple G2-tree of the ray over GF(2) that belongs to it.
#
#   julia --project=julia julia/to_tex/cubic_tree_table.jl [--edge-length=LENGTH] [--standalone] [--output=FILE]
#
# (or sh julia/to_tex/cubic_tree_table.sh with the same options). With
# --standalone, the table is the document of standalone_figure.jl.
#
# Each cubic belongs to one of the three tetrahedra of the G2-Dressian. Its
# first monomial has the coefficient 2 and belongs to the ray that exists only
# over GF(2), in the interior of the tetrahedron: there it alone attains the
# minimum. Each other monomial belongs to a vertex of the tetrahedron: there
# it alone does not attain the minimum. The script certifies both statements
# before it draws the trees with render_simple_tree.jl.
###############################################################################

include(joinpath(@__DIR__, "render_simple_tree.jl"))

# One line per monomial: its ray, its sign or coefficient, and its three
# Pluecker coordinates. An empty line separates the cubics.
const CUBIC_TREE_TABLE_MONOMIALS = """
52 2 45 46 56
34 + 23 36 56
9 - 14 12 45
40 + 26 13 45
6 - 35 12 46

54 2 23 12 13
33 - 46 14 13
10 + 25 56 23
41 + 16 45 23
7 - 34 56 12

53 2 46 56 45
8 + 12 25 45
30 - 36 13 46
12 + 15 23 46
11 - 24 13 56
"""

# The table has the booktabs form of the tables of main.tex: \toprule and
# \bottomrule frame it, and it has no heading, so no \midrule. This space
# stands under the trees of each cubic, before the next cubic or the bottom
# rule. A tree is deeper than the strut of its row, so
# \tabularnewline[dimen] would add nothing under it.
const CUBIC_TREE_TABLE_TREE_SKIP = raw"\addlinespace[4pt]"
# The strut keeps the monomials clear of the trees or the rule above them.
const CUBIC_TREE_TABLE_STRUT = raw"\rule{0pt}{3ex}"
# The space between the monomials and the trees under them.
const CUBIC_TREE_TABLE_MONOMIAL_SKIP = "4pt"

"""
    cubic_tree_table_tex(; edge_length=0.4, standalone=false)

The table of the cubics, after the certificate that each monomial alone
attains or alone misses the minimum at its ray. With `standalone=true`, the
document of `g2_standalone_figure`.
"""
function cubic_tree_table_tex(; edge_length::Real=0.4, standalone::Bool=false)
    source = load_g2_maximal_cell_source(; field=:gf2)
    coordinate = Dict(pair => index for (index, pair) in enumerate(PLUECKER_PAIRS))
    cubics = [
        [(ray=parse(Int, fields[1]), sign=fields[2], pluecker=fields[3:5],
          variables=Tuple.(collect.(fields[3:5])))
         for fields in split.(split(cubic, '\n'))]
        for cubic in split(strip(CUBIC_TREE_TABLE_MONOMIALS), "\n\n")
    ]
    trees = Dict{Int,String}()
    for (number, cubic) in enumerate(cubics)
        # The tropical value of every monomial at the ray of every monomial.
        tropical = [
            [sum(row_as_vector(source.balanced_rays, at.ray)[
                 coordinate[(parse(Int, i), parse(Int, j))]] for (i, j) in monomial.variables)
             for monomial in cubic]
            for at in cubic
        ]
        centre = first(cubic).ray
        centre > 51 || error("cubic $number: ray $centre also exists over QQ")
        around = unique!(reduce(vcat, [collect(cell) for cell in source.cells if centre in cell]))
        sort!(filter(!=(centre), around)) == sort([monomial.ray for monomial in cubic[2:end]]) ||
            error("cubic $number: its rays are not the vertices of the tetrahedron of ray $centre")
        findall(==(minimum(tropical[1])), tropical[1]) == [1] ||
            error("cubic $number: the first monomial is not the only minimum at ray $centre")
        for position in 2:length(cubic)
            findall(>(minimum(tropical[position])), tropical[position]) == [position] || error(
                "cubic $number: monomial $position is not the only one above the minimum " *
                "at ray $(cubic[position].ray)",
            )
        end
        for monomial in cubic
            trees[monomial.ray] = g2_simple_tree_tex(g2_ray_tree(monomial.ray; source=source);
                                                     edge_length=edge_length)
        end
    end
    table = sprint() do io
        println(io, "% Generated by julia/to_tex/cubic_tree_table.sh.")
        println(io, raw"\begin{tabular}{@{}ccccc@{}}")
        println(io, raw"\toprule")
        for cubic in cubics
            separator = CUBIC_TREE_TABLE_STRUT
            for monomial in cubic
                lead = monomial.sign == "2" ? "2" : monomial.sign * raw"\,"
                print(io, separator, "\$", lead, join(("p_{$pair}" for pair in monomial.pluecker)), "\$")
                separator = " & "
            end
            println(io, " \\tabularnewline[", CUBIC_TREE_TABLE_MONOMIAL_SKIP, "]")
            print(io, join((trees[monomial.ray] for monomial in cubic), "&\n"))
            println(io, raw"\tabularnewline")
            println(io, CUBIC_TREE_TABLE_TREE_SKIP)
        end
        println(io, raw"\bottomrule")
        println(io, raw"\end{tabular}")
    end
    return standalone ? g2_standalone_figure(table) : table
end

function cubic_tree_table_main(args=ARGS)
    usage = "Usage: julia --project=julia julia/to_tex/cubic_tree_table.jl " *
            "[--edge-length=LENGTH] [--standalone] [--output=FILE]"
    if "--help" in args
        println(usage)
        return nothing
    end
    for arg in args
        arg == "--standalone" || startswith(arg, "--edge-length=") || startswith(arg, "--output=") ||
            throw(ArgumentError("unknown option $arg; $usage"))
    end
    g2_tree_option(args, "output") == "" && throw(ArgumentError("output path must not be empty"))
    edge_length = parse(Float64, something(g2_tree_option(args, "edge-length"), "0.4"))
    return g2_tree_emit(args, cubic_tree_table_tex(; edge_length, standalone="--standalone" in args))
end

if abspath(PROGRAM_FILE) == @__FILE__
    cubic_tree_table_main()
end
