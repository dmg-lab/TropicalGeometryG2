###############################################################################
# The paper table of the ray orbits of the maximal cells of the tropical
# G2-Grassmannian, in characteristic 0 and in characteristic 2: for every
# orbit of maximal cells, numbered as in the tables of maximal trees, the
# article labels of the ray orbits of its rays.
#
# Run from julia/ with `julia --project=.`. The script reads the support cells
# and their ray orbits from the G2-tree atlas. It prints the tabular, or writes
# it to --output=FILE; main.tex supplies the float and its caption, and loads
# booktabs for its rules.
###############################################################################

include(joinpath(@__DIR__, "build_styled_ray_orbit_tables.jl"))
include(joinpath(@__DIR__, "toric_degeneration_table.jl"))

# The table has this many rows; its columns follow each other.
const CELL_RAY_TABLE_ROWS = 7
# The table has the booktabs form of the tables of main.tex: the \arraystretch
# of its rows, and the width that its column gaps stretch to fill.
const CELL_RAY_TABLE_STRETCH = 0.9
const CELL_RAY_TABLE_WIDTH = "\\linewidth"
# The color of the ray-orbit labels, as \raytype in main.tex: black.
const CELL_RAY_TABLE_RAY_COLOR = "000000"

"""The position of a data ray orbit in the article order α₁, …, ε of the catalog."""
cell_ray_table_rank(orbit::Int) = findfirst(==(orbit), PAPER_RAY_CATALOG_ORDER)

"""
The ray orbits of a polygon in article order: sorted for a triangle, and for
a quadrilateral in cyclic order, from the least label and in the direction
that is least.
"""
function cell_ray_table_orbits(orbits::Vector{Int})
    length(orbits) == 3 && return sort(orbits; by=cell_ray_table_rank)
    length(orbits) == 4 || error("a maximal cell has 3 or 4 rays, not $(length(orbits))")
    readings = [circshift(direction, -shift) for direction in (orbits, reverse(orbits))
                for shift in 0:3]
    return argmin(reading -> cell_ray_table_rank.(reading), readings)
end

"""
The maximal-cell orbits of both fields in atlas order: their `number`, the
data ray orbits of their support cell, and whether it is a quadrilateral.
"""
function cell_ray_table_rows()
    rows = []
    for row in toric_table_csv_rows(TORIC_TABLE_ATLAS)
        all(field -> field in ("qq", "gf2"), split(row["fields"], '+')) || continue
        number = toric_table_label_number(row["label"])
        any(other -> other.number == number, rows) && continue
        orbits = parse.(Int, split(row["polygon_ray_orbits"], ';'))
        length(orbits) == length(split(row["support"], ';')) ||
            error("atlas label $(row["label"]) has $(length(orbits)) ray orbits for its support")
        push!(rows, (number=number, orbits=cell_ray_table_orbits(orbits)))
    end
    sort!(rows; by=row -> row.number)
    [row.number for row in rows] == collect(1:length(rows)) ||
        error("the atlas does not number the maximal-cell orbits 1, 2, ...")
    return rows
end

"""One entry: the bold old-style number of the orbit and the labels of its ray orbits."""
function cell_ray_table_entry(row)
    labels = join(("\\textcolor{g2RayLabel}{\\boldmath\$$(paper_ray_article_label(orbit))\$}"
                   for orbit in row.orbits), ", ")
    return "\\textcolor{g2CellLabel}{\\bfseries\\boldmath\\oldstylenums{$(row.number)}}: $labels"
end

"""The input-ready tabular: the orbits in columns of `CELL_RAY_TABLE_ROWS` rows."""
function cell_ray_orbit_table_tex()
    rows = cell_ray_table_rows()
    columns = cld(length(rows), CELL_RAY_TABLE_ROWS)
    io = IOBuffer()
    println(io, "% Generated by julia/to_tex/cell_ray_orbit_table.jl from ",
            "julia/studies/g2/atlas/flag/local_flag_cell_atlas.csv.")
    println(io, "\\begingroup")
    println(io, "\\definecolor{g2CellLabel}{HTML}{$TORIC_TABLE_LABEL_COLOR}")
    println(io, "\\definecolor{g2RayLabel}{HTML}{$CELL_RAY_TABLE_RAY_COLOR}")
    println(io, "\\renewcommand{\\arraystretch}{$CELL_RAY_TABLE_STRETCH}")
    println(io, "\\begin{tabular*}{$CELL_RAY_TABLE_WIDTH}{@{\\extracolsep{\\fill}}",
            repeat("l", columns), "@{}}")
    println(io, "  \\toprule")
    for line in 1:CELL_RAY_TABLE_ROWS
        entries = String[]
        for column in 1:columns
            index = (column - 1) * CELL_RAY_TABLE_ROWS + line
            push!(entries, index <= length(rows) ? cell_ray_table_entry(rows[index]) : "")
        end
        println(io, "  ", join(entries, " & "), " \\tabularnewline")
    end
    println(io, "  \\bottomrule")
    println(io, "\\end{tabular*}%")
    println(io, "\\endgroup")
    return String(take!(io))
end

function cell_ray_orbit_table_main(args=ARGS)
    if "--help" in args
        println("Usage: julia --project=. to_tex/cell_ray_orbit_table.jl [--output=FILE]")
        return nothing
    end
    for arg in args
        startswith(arg, "--output=") || throw(ArgumentError("unknown option $arg; use --help"))
    end
    outputs = [arg for arg in args if startswith(arg, "--output=")]
    length(outputs) <= 1 || throw(ArgumentError("pass only one --output"))
    tex = cell_ray_orbit_table_tex()
    if isempty(outputs)
        print(tex)
    else
        path = split(only(outputs), '='; limit=2)[2]
        mkpath(dirname(abspath(path)))
        write(path, tex)
        println("Wrote ", path)
    end
    return nothing
end

if abspath(PROGRAM_FILE) == @__FILE__
    cell_ray_orbit_table_main()
end
