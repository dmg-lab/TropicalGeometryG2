###############################################################################
# The paper tables of the G2-trees of the maximal cells of the tropical
# G2-Grassmannian, in characteristic 0 and in characteristic 2: one tree per
# orbit. One table has the cells that yield a toric degeneration, with the
# labels and in the order of toric_degeneration_table.jl; with --non-toric,
# the other has the remaining cells, whose labels continue these.
#
# Run from julia/ with `julia --project=.`. The panels are those of the ray
# catalog of build_styled_ray_orbit_tables.jl, which this file includes, fitted
# to their trees. The script prints the tabular, or writes it to --output=FILE;
# main.tex supplies the float and its caption.
###############################################################################

include(joinpath(@__DIR__, "build_styled_ray_orbit_tables.jl"))
include(joinpath(@__DIR__, "toric_degeneration_table.jl"))

# The columns of the two tables, and the width in centimetres that their widest
# headings needed at the 12pt of main.tex when they still read "size":
# "18 char 2 6" and "33 char ≠ 2 3". Four panels of the second width
# would exceed the text width of main.tex.
const TORIC_TREE_TABLE_LAYOUT = (
    toric=(columns=4, minimum_width=3.9),
    other=(columns=3, minimum_width=4.7),
)

# The note of a panel whose orbit belongs to one field only. By main.tex the
# fan over QQ is that of every characteristic other than 2.
const TORIC_TREE_TABLE_NOTE = (qq=raw"char\ \(\neq 2\)", gf2=raw"char\ 2")

# The mark at the top right of the panel of a quadrilateral cell; the other
# maximal cells are triangles and have none. It is as high as the digits of
# the heading and takes no depth.
const TORIC_TREE_TABLE_SQUARE =
    raw"\smash[b]{\tikz[baseline=0pt]\draw[g2TreeRule,line width=1pt] (0,0) rectangle (2.6mm,2.6mm);}"

"""The panel of a row: its number, its orbit size, the tree of its cell, and a square if the cell is a quadrilateral."""
function toric_tree_table_panel(io::IO, row, options)
    fields = first.(row.orbits)
    styled_tree_panel(
        io, styled_tree_label("\\oldstylenums{$(toric_table_label_number(row.label))}",
                              row.orbit_size, options),
        styled_tree_tikz(row.tree, options);
        note=length(fields) == length(TORIC_TABLE_FIELDS) ? "" :
             TORIC_TREE_TABLE_NOTE[only(fields)],
        corner=length(row.support) == 4 ? TORIC_TREE_TABLE_SQUARE : "",
    )
end

"""
    toric_degeneration_tree_table_tex(; toric=true, palette=:grayscale,
                                      label=false, scale=1.0, taxon_scale=1.0,
                                      bounded_length=0.70, edge_labels=:disk,
                                      standalone=false)

Return the input-ready table of trees: one panel per toric support orbit, in
the order and with the labels of `toric_degeneration_table_tex`. With
`toric=false` the panels are the support orbits that are not toric. The
drawing options are those of `g2_tree_tikz`. The panels are fitted to their
trees, so `scale` also scales the table. Pass `standalone=true` for the
document of `g2_standalone_figure`.
"""
function toric_degeneration_tree_table_tex(; toric::Bool=true, standalone::Bool=false,
                                           drawing...)
    options = styled_tree_table_options(;
        bounded_length=G2_TREE_BOUNDED_DRAW_LENGTH, color=TORIC_TABLE_LABEL_COLOR,
        drawing...,
    )
    rows = toric_tree_table_rows(; toric=toric)
    layout = toric ? TORIC_TREE_TABLE_LAYOUT.toric : TORIC_TREE_TABLE_LAYOUT.other
    fragment = sprint() do io
        println(io, "% Generated by julia/to_tex/toric_degeneration_tree_table.jl; ",
                toric ? "the panels are the rows of toric_degeneration_table.jl." :
                        "the panels are the atlas orbits that are not toric (--non-toric).")
        styled_tree_grid(io, length(rows), options; tight=true, layout...,
                         groups=[first.(row.orbits) for row in rows]) do io, position
            toric_tree_table_panel(io, rows[position], options)
        end
    end
    return standalone ? g2_standalone_figure(fragment) : fragment
end

function toric_degeneration_tree_table_main(args=ARGS)
    toric = !("--non-toric" in args)
    return styled_tree_table_main(
        (; options...) -> toric_degeneration_tree_table_tex(; toric=toric, options...), args;
        script="toric_degeneration_tree_table.jl",
        flags=("--non-toric",),
        bounded_length=G2_TREE_BOUNDED_DRAW_LENGTH,
        stem=toric ? "g2_toric_degeneration_trees" : "g2_non_toric_cell_trees",
        caption="The \$\\Ggroup\$-trees of the maximal cells that yield " *
                (toric ? "a toric degeneration, indexed as the table of the " *
                         "Newton--Okounkov polytopes" : "no toric degeneration") *
                "; a cell marked char\\ \$\\neq 2\$ or char\\ 2 is maximal only in " *
                "these characteristics.",
    )
end

if abspath(PROGRAM_FILE) == @__FILE__
    toric_degeneration_tree_table_main()
end
