#
#   Conjecture "decomposition": Minkowski sums of subword polytopes
#
###############################################################################

"""
    reduced_subwords(W::WeylGroup, r::Vector{Int}, target::WeylGroupElem)

All position sets `I = [k_1 < ... < k_m]` such that the subword of the paper
word `r` at those positions is a reduced expression for `target`, i.e.

    s_{r[k_m]} * ... * s_{r[k_1]} == target   and   m == length(target).

These are the embeddings the decomposition conjecture asks for.
"""
function reduced_subwords(W::WeylGroup, r::Vector{Int}, target::WeylGroupElem)
  l = length(r)
  m = length(target)
  out = Vector{Vector{Int}}()
  chosen = Int[]

  function rec(k::Int, u)
    len = length(chosen)
    if len == m
      u == target && push!(out, copy(chosen))
      return
    end
    # not enough letters left
    (l - k + 1) < (m - len) && return
    k > l && return
    # skip position k
    rec(k + 1, u)
    # take position k: multiply on the LEFT, must increase length
    uu = gen(W, r[k]) * u
    if length(uu) == len + 1
      push!(chosen, k)
      rec(k + 1, uu)
      pop!(chosen)
    end
  end

  rec(1, one(W))
  return out
end

"""
    decomposition_polytope(D::ChevalleyData, choices) -> Polyhedron

Given, for each `j` with `varpi[j] != 0`, a position set `I_j` returned by
`reduced_subwords`, form

    sum_j varpi[j] * iota_j( P_{G/P_j, omega_j, s_j} )

as in Conjecture "decomposition", where `iota_j` places coordinate `t` of the
`j`-th factor at position `I_j[t]` of `Z^l`.

`choices` is a vector of pairs `j => I_j`.
"""
function decomposition_polytope(D::ChevalleyData, choices::Vector{<:Pair{Int,<:Vector{Int}}})
  l = length(D.r)
  type_rk = _type_and_rank(D.R)
  summands = Polyhedron[]
  for (j, I) in choices
    c = D.varpi[j]
    iszero(c) && continue
    omega = zeros(Int, rank(D.R))
    omega[j] = 1
    subword = [D.r[k] for k in I]
    Dj = chevalley_data(type_rk[1], type_rk[2], omega; word=subword)
    Pj = chevalley_polytope(Dj)
    rows = Vector{Vector{QQFieldElem}}()
    for v in vertices(Pj)
      e = zeros(QQFieldElem, l)
      for (t, k) in enumerate(I)
        e[k] = v[t]
      end
      push!(rows, c .* e)
    end
    push!(summands, convex_hull(matrix(QQ, reduce(vcat, [permutedims(x) for x in rows]))))
  end
  @req !isempty(summands) "no summands"
  Q = summands[1]
  for k in 2:length(summands)
    Q = minkowski_sum(Q, summands[k])
  end
  return Q
end

"""
    check_decomposition(D::ChevalleyData) -> NamedTuple

Search over all admissible subword embeddings for a decomposition of
`P_{X,varpi,s}` as the Minkowski sum predicted by Conjecture "decomposition",
and report the first one that works (if any).
"""
function check_decomposition(D::ChevalleyData)
  P = chevalley_polytope(D)
  js = [j for j in 1:rank(D.R) if D.varpi[j] != 0]
  per_j = Dict{Int,Vector{Vector{Int}}}()
  for j in js
    omega = zeros(Int, rank(D.R))
    omega[j] = 1
    wPj = minimal_coset_representative(D.W, parabolic_indices(omega))
    per_j[j] = reduced_subwords(D.W, D.r, wPj)
  end
  for combo in Iterators.product((per_j[j] for j in js)...)
    choices = [js[t] => collect(combo[t]) for t in 1:length(js)]
    Q = try
      decomposition_polytope(D, choices)
    catch
      continue
    end
    if Q == P
      return (found=true, choices=choices, polytope=Q)
    end
  end
  return (found=false, choices=nothing, polytope=nothing)
end

# Recover (type, rank) from a root system so that sub-data can be rebuilt.
function _type_and_rank(R)
  t = root_system_type(R)
  @req length(t) == 1 "only simple root systems are supported"
  return t[1]
end

