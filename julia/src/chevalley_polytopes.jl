###############################################################################
#
#   ChevalleyPolytopes
#
#   A general implementation of the Chevalley polytopes of
#
#       P. Spacek, C. Wang, "Chevalley Polytopes and Newton-Okounkov bodies",
#       arXiv:2411.10276
#
#   For a triple (X, varpi, s) consisting of
#
#     * a homogeneous space X = G/P for G simple simply-connected over C,
#     * a dominant integral weight varpi whose highest weight line is
#       stabilised by P, giving X <-> P(V_varpi),
#     * a reduced expression s for the minimal coset representative w^P of
#       w_0 W_P,
#
#   the paper defines a valuation nu_{X,varpi,s} : C[X] -> Z^l  (l = dim X)
#   and sets
#
#       P_{X,varpi,s} = conv( nu(p) : p in C[X], deg(p) = 1 ).
#
#   This file computes that polytope from scratch: root system, Weyl group,
#   minimal coset representative, the irreducible module V_varpi with its
#   lowering operators, the torus expansion u_- . v_varpi over Q[a_1..a_l],
#   the degrevlex-minimal terms, and the convex hull.
#
#   Requires Oscar (developed against 1.8.1).  Load with
#
#       using TropicalGeometryG2
#
###############################################################################

module ChevalleyPolytopes

using Oscar

