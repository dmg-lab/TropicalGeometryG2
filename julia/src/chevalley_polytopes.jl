"""
    ChevalleyData

Everything computed for one triple `(X, varpi, s)`.  Fields:

  * `R`, `W`, `L`, `V`  -- root system, Weyl group, Lie algebra, module V_varpi
  * `varpi`             -- dominant weight in fundamental weight coordinates
  * `S`                 -- indices generating W_P
  * `wP`                -- minimal coset representative
  * `r`                 -- the paper word [r_1, ..., r_l]
  * `weights`           -- weight of each basis vector of `V`, in fundamental
                           weight coordinates
  * `hw_index`          -- index of the highest weight vector in that basis
  * `ring`, `a`         -- Q[a_1..a_l] and the variables, `a[k]` for position k
  * `ordering`          -- degrevlex with a_l > ... > a_1
  * `torus_vector`      -- coordinates of u_-(a) . v_varpi; entry `k` is the
                           restriction to X^o of the coordinate function dual
                           to the `k`-th basis vector of `V`
  * `basis_valuations`  -- nu of each of those coordinate functions
  * `valuation_image`   -- the full, basis-independent set of values of nu on
                           the degree-1 part C[X]_1 (see `adapted_valuations`)
"""
struct ChevalleyData
  R::Any
  W::Any
  L::Any
  V::Any
  varpi::Vector{Int}
  S::Vector{Int}
  wP::Any
  r::Vector{Int}
  weights::Vector{Vector{Int}}
  hw_index::Int
  ring::Any
  a::Vector{Any}
  ordering::Any
  torus_vector::Vector{Any}
  basis_valuations::Vector{Vector{Int}}
  valuation_image::Vector{Vector{Int}}
end

function Base.show(io::IO, D::ChevalleyData)
  print(io, "Chevalley data for varpi = ", D.varpi,
    ", w^P of length ", length(D.r),
    ", word (paper convention) ", D.r)
end

"""
    weight_multiplicities(D::ChevalleyData) -> Dict{Vector{Int}, Int}

Multiplicities of the weights of `V_varpi`.  Weight spaces of dimension > 1
are exactly the places where the paper's notion of a *Chevalley basis for
V_varpi* involves a genuine choice (see the vectors `a`, `b`, `c` in the
A_3 example of Appendix A.1); Oscar's `simple_module` supplies some weight
basis, not necessarily that one.  The polytope itself does not depend on the
choice -- see `valuation_image`.
"""
function weight_multiplicities(D::ChevalleyData)
  mult = Dict{Vector{Int},Int}()
  for w in D.weights
    mult[w] = get(mult, w, 0) + 1
  end
  return mult
end

# -- lowering operators as sparse columns ------------------------------------
#
# Fcol[i][j] is the list of (row, coefficient) with f_i . b_j = sum coeff * b_row.

function _lowering_columns(L, V, n::Int)
  _, ys, _ = chevalley_basis(L)
  dV = dim(V)
  Fcol = [[Tuple{Int,QQFieldElem}[] for _ in 1:dV] for _ in 1:n]
  for i in 1:n
    fi = ys[i]                      # negative root vector of the i-th SIMPLE root:
                                    # simple_roots(R) == positive_roots(R)[1:rank]
    for j in 1:dV
      img = fi * basis(V, j)
      for (row, c) in enumerate(coefficients(img))
        if !iszero(c)
          push!(Fcol[i][j], (row, QQ(c)))
        end
      end
    end
  end
  return Fcol
end

# -- weights of the basis vectors --------------------------------------------

"""
    basis_weights(L, V) -> Vector{Vector{Int}}

The weight of each basis vector of the `L`-module `V`, in fundamental weight
coordinates. The basis must be a weight basis, as that of `simple_module` and
of its exterior powers is.
"""
function basis_weights(L, V)
  _, _, hs = chevalley_basis(L)
  n = length(hs)
  dV = dim(V)
  wts = Vector{Vector{Int}}(undef, dV)
  for j in 1:dV
    bj = basis(V, j)
    w = Vector{Int}(undef, n)
    for i in 1:n
      img = hs[i] * bj
      cs = collect(coefficients(img))
      # the basis of `simple_module` is a weight basis, so h_i acts diagonally
      for (row, c) in enumerate(cs)
        @req row == j || iszero(c) "basis of V is not a weight basis (h_$i is not diagonal)"
      end
      c = cs[j]
      @req is_one(denominator(QQ(c))) "non-integral weight coordinate"
      w[i] = Int(numerator(QQ(c)))
    end
    wts[j] = w
  end
  return wts
end

# -- exp(t * f_i) acting on a vector with polynomial coordinates -------------

function _apply_f(Fcol_i, v::Vector{T}, Ra) where {T}
  w = T[zero(Ra) for _ in 1:length(v)]
  for j in 1:length(v)
    iszero(v[j]) && continue
    for (row, c) in Fcol_i[j]
      w[row] += c * v[j]
    end
  end
  return w
end

function _exp_f(Fcol_i, t, v::Vector{T}, Ra) where {T}
  result = copy(v)
  term = copy(v)
  m = 0
  while true
    m += 1
    term = _apply_f(Fcol_i, term, Ra)
    all(iszero, term) && break
    term = T[(t * x) * QQ(1, m) for x in term]     # t^m f^m / m!
    result = result .+ term
    @req m <= 10_000 "expansion of exp(t*f) failed to terminate"
  end
  return result
end

# -- degrevlex-minimal exponent vector ---------------------------------------
#
# `monomials(f; ordering = o)` lists the monomials in DECREASING order, so the
# minimal one is the last.  The exponent vector comes back in ring variable
# order, which is (a_l, ..., a_1); we reverse it to the reported order
# (a_1, ..., a_l).

"""
    minimal_exponent(f, o) -> Vector{Int}

The valuation of the polynomial `f` of a torus expansion: the exponent vector of
its `o`-minimal term, in the reported order (a_1, ..., a_l).
"""
function minimal_exponent(f, o)
  @req !iszero(f) "the zero polynomial has no valuation"
  mons = collect(monomials(f; ordering=o))
  return reverse(exponent_vector(mons[end], 1))
end

function _min_term(f, o)
  ts = collect(terms(f; ordering=o))
  return ts[end]
end

# -- the basis-independent valuation image -----------------------------------
#
# nu is a valuation on the l-dimensional space C[X]_1, so there is a basis
# whose nu-values are pairwise distinct, and then nu(C[X]_1 \ 0) is exactly
# that set of values.  Starting from any spanning set we reduce: whenever two
# elements share a value, subtract to cancel the common minimal term.  This
# terminates because degrevlex is a well-order on Z^l_{>=0}.

"""
    adapted_valuations(polys::Vector, o) -> Vector{Vector{Int}}

The values of the valuation on the span of `polys`, sorted: the minimal
exponents of an adapted basis.
"""
function adapted_valuations(polys::Vector, o)
  work = [f for f in polys if !iszero(f)]
  seen = Dict{Vector{Int},Any}()          # exponent vector -> reduced polynomial
  while !isempty(work)
    f = pop!(work)
    while true
      iszero(f) && break
      e = minimal_exponent(f, o)
      if haskey(seen, e)
        g = seen[e]
        cf = leading_coefficient(_min_term(f, o))
        cg = leading_coefficient(_min_term(g, o))
        f = f - (cf // cg) * g
      else
        seen[e] = f
        break
      end
    end
  end
  return sort!(collect(keys(seen)))
end

"""
    torus_expansion(L, V, highest::Int, word::Vector{Int}) -> NamedTuple

The torus expansion `u_-(a) . b` of the basis vector number `highest` of the
`L`-module `V`, for the paper word `word`: `(ring, a, ordering, vector)` as in
`ChevalleyData`, `vector` holding the coordinates in the basis of `V`.
`chevalley_data` expands the highest weight vector of `V_varpi` along a word
of `w^P`; here `V` may be any module, e.g. `/\\^2 V_7` for G_2, and `word`
any word, e.g. one of `w_0`, whose valuation is defined on all of `C[G/B]`.
"""
function torus_expansion(L, V, highest::Int, word::Vector{Int})
  Fcol = _lowering_columns(L, V, rank(root_system(L)))
  l = length(word)

  # Q[a_1, ..., a_l] with the variables CREATED in the order a_l > ... > a_1,
  # so that Oscar's degrevlex is exactly the order the paper prescribes.
  Ra, gs = polynomial_ring(QQ, ["a$k" for k in l:-1:1])
  a = Any[gs[l + 1 - k] for k in 1:l]          # a[k] is the variable for position k
  o = degrevlex(Ra)

  # u_-(a) . b, applying y_{r_1}(a_1) first (rightmost factor of s).
  v = Any[zero(Ra) for _ in 1:dim(V)]
  v[highest] = one(Ra)
  for k in 1:l
    v = _exp_f(Fcol[word[k]], a[k], v, Ra)
  end
  return (ring=Ra, a=a, ordering=o, vector=v)
end

"""
    chevalley_data(type::Symbol, rk::Int, varpi::Vector{Int};
                   word::Union{Nothing,Vector{Int}} = nothing) -> ChevalleyData

Compute everything attached to the triple `(X, varpi, s)`.

`type`/`rk` name the root system in Oscar's convention (`:A`, `:B`, `:C`,
`:D`, `:E`, `:F`, `:G`), `varpi` is the dominant weight in fundamental weight
coordinates, and `word` is the reduced expression for `w^P` **in the paper's
convention** (`r[1]` is the rightmost letter of `s`).  If `word` is omitted,
Oscar's default reduced word for `w^P` is used.

# Example

    D = chevalley_data(:G, 2, [0, 1])          # the adjoint G_2-Grassmannian
    P = chevalley_polytope(D)
"""
function chevalley_data(type::Symbol, rk::Int, varpi::Vector{Int};
  word::Union{Nothing,Vector{Int}}=nothing)

  R = root_system(type, rk)
  W = weyl_group(R)
  n = rank(R)
  @req length(varpi) == n "varpi has the wrong number of coordinates"
  @req all(>=(0), varpi) "varpi must be dominant"
  @req any(>(0), varpi) "varpi must be non-zero"

  S = parabolic_indices(varpi)
  wP = minimal_coset_representative(W, S)

  r = isnothing(word) ? paper_word(wP) : copy(word)
  @req length(r) == length(wP) "the given word is not reduced (wrong length)"
  @req W(reverse(r)) == wP "the given word does not represent w^P"

  l = length(r)
  dimX, degX = degree_of_embedding(R, varpi)
  @req dimX == l "internal inconsistency: dim X != length(w^P)"

  L = lie_algebra(QQ, type, rk)
  V = simple_module(L, varpi)
  dV = dim(V)

  wts = basis_weights(L, V)
  hw_candidates = findall(==(varpi), wts)
  @req length(hw_candidates) == 1 "the highest weight space is not one-dimensional"
  hw = hw_candidates[1]

  # u_-(a) . v_varpi
  Ra, a, o, v = torus_expansion(L, V, hw, r)

  basis_vals = Vector{Vector{Int}}(undef, dV)
  for j in 1:dV
    @req !iszero(v[j]) "coordinate function $j restricts to zero on the torus"
    basis_vals[j] = minimal_exponent(v[j], o)
  end

  image = adapted_valuations(collect(v), o)

  # nu is a valuation on the dim(V)-dimensional space C[X]_1 with values in the
  # totally ordered group (Z^l, degrevlex), so it admits an adapted basis and
  # its image has EXACTLY dim(V) elements.  This is a strong consistency check
  # on the torus expansion, the term order and the reduction above.
  @req length(image) == dim(V) "valuation image has $(length(image)) values, expected dim(V) = $(dim(V))"

  return ChevalleyData(R, W, L, V, varpi, S, wP, r, wts, hw,
    Ra, a, o, collect(v), basis_vals, image)
end

"""
    chevalley_polytope(D::ChevalleyData; use_image::Bool = true) -> Polyhedron

The Chevalley polytope `P_{X,varpi,s}`.

With `use_image = true` (the default) the convex hull is taken over the full
valuation image of `C[X]_1`, which is what the definition asks for and is
independent of any choice of basis of `V_varpi`.  With `use_image = false`
only the valuations of the coordinate functions of Oscar's weight basis are
used; the two agree exactly when that basis is adapted to the valuation,
which `is_adapted_basis` reports.
"""
function chevalley_polytope(D::ChevalleyData; use_image::Bool=true)
  pts = use_image ? D.valuation_image : D.basis_valuations
  return convex_hull(matrix(QQ, reduce(vcat, [permutedims(p) for p in pts])))
end

"""
    is_adapted_basis(D::ChevalleyData) -> Bool

Whether the weight basis Oscar supplies for `V_varpi` already realises every
value of the valuation, i.e. whether its coordinate functions have pairwise
distinct valuations.  When this is `false` the basis is not a Khovanskii-style
"Chevalley basis" in the sense of the paper, and only `valuation_image` is
meaningful.
"""
function is_adapted_basis(D::ChevalleyData)
  return length(unique(D.basis_valuations)) == length(D.basis_valuations)
end

