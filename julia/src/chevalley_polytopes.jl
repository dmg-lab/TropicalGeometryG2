"""
    normalised_volume_of(P::Polyhedron) -> ZZRingElem

The lattice (normalised) volume, i.e. `dim(P)! * euclidean volume`, which is
what the paper compares against `deg(X)`.
"""
normalised_volume_of(P::Polyhedron) = numerator(normalized_volume(P))

"""
    has_idp(P::Polyhedron) -> Bool

Whether the lattice points of `P` form a Hilbert basis for the cone over
`{1} x P`, equivalently whether `P` has the integer decomposition property.
This is the Polymake check the paper describes as evidence for the Khovanskii
basis conjecture.
"""
function has_idp(P::Polyhedron)
  vs = [Vector{QQFieldElem}(v) for v in vertices(P)]
  rows = [permutedims(vcat(QQ(1), v)) for v in vs]
  C = positive_hull(matrix(QQ, reduce(vcat, rows)))
  return all(h -> is_one(h[1]), hilbert_basis(C))
end

"""
    verify_chevalley(D::ChevalleyData) -> NamedTuple

Run the checks of Appendix A on one triple: compare the normalised volume of
the Chevalley polytope with the Borel-Hirzebruch degree of `X` (Conjecture
"nobody"), and test the integer decomposition property (Conjecture
"khovanskii").
"""
function verify_chevalley(D::ChevalleyData)
  P = chevalley_polytope(D)
  dimX, degX = degree_of_embedding(D.R, D.varpi)
  vol = normalised_volume_of(P)
  return (
    word=D.r,
    dim=dimX,
    degree=degX,
    volume=vol,
    is_nobody=(vol == degX),
    n_vertices=n_vertices(P),
    idp=has_idp(P),
    adapted_basis=is_adapted_basis(D),
    polytope=P,
  )
end

###############################################################################
#
#   Writing polymake files
#
#   Oscar's `Polyhedron` is a thin wrapper around a polymake `BigObject`, held
#   in the `pm_polytope` field.  Writing that subobject with `Polymake.save`
#   produces a native polymake file (polymake 4.x JSON, conventionally with
#   the extension `.poly`) that `polymake`'s own `load` reads directly, with
#   no Oscar involved.
#
#   Metadata travels as polymake *attachments*: they survive save/load and are
#   readable from polymake as `$p->get_attachment("CHEVALLEY_WORD")`.  Note
#   that setting `description` through `Polymake.call_method` does NOT persist,
#   which is why attachments are used here; the object name (settable with
#   `setname!`) is stored as `_id`.
#
###############################################################################

"""
    save_polymake(P::Polyhedron, filename::AbstractString;
                  name = nothing, attachments = Dict(), canonical = false)

Write `P` to `filename` as a polymake file by calling `Polymake.save` on the
underlying `pm_polytope` subobject.

`name` is stored as the polymake object name (`_id` in the file), and each
entry of `attachments` becomes a polymake attachment.  Attachment values
should be strings, which polymake stores and returns verbatim.
"""
function save_polymake(P::Polyhedron, filename::AbstractString;
  name::Union{Nothing,AbstractString}=nothing,
  attachments::AbstractDict=Dict{String,String}(),
  canonical::Bool=false)

  o = P.pm_polytope
  isnothing(name) || Oscar.Polymake.setname!(o, String(name))
  for k in sort(collect(keys(attachments)))
    Oscar.Polymake.attach(o, String(k), string(attachments[k]))
  end
  dir = dirname(abspath(filename))
  isempty(dir) || mkpath(dir)
  Oscar.Polymake.save(o, String(filename); canonical=canonical)
  return filename
end

"""
    polytope_name(D::ChevalleyData) -> String

A stable, self-describing name for the polytope of `D`, e.g.
`"chevalley-G2-varpi_0-1-word_2-1-2-1-2"`.
"""
function polytope_name(D::ChevalleyData)
  t = _type_and_rank(D.R)
  return string("chevalley-", t[1], t[2],
    "-varpi_", join(D.varpi, "-"),
    "-word_", join(D.r, "-"))
end

"""
    save_chevalley_polytope(D::ChevalleyData, dir::AbstractString;
                            precompute::Bool = true) -> String

Compute the Chevalley polytope of `D` and write it to
`dir/<polytope_name(D)>.poly` via [`save_polymake`](@ref), tagged with the
data it came from.  Returns the path.

With `precompute = true` the vertices, facets, lattice points and normalised
volume are computed before saving, so the resulting file is usable in polymake
without recomputation.

The attachments written are `CHEVALLEY_ROOT_SYSTEM`, `CHEVALLEY_VARPI`,
`CHEVALLEY_WORD` (the paper word `r_1 ... r_l`), `CHEVALLEY_DIM_X`,
`CHEVALLEY_DEGREE_X`, `CHEVALLEY_NORMALISED_VOLUME`, `CHEVALLEY_IS_NOBODY`,
`CHEVALLEY_HAS_IDP` and `CHEVALLEY_SOURCE`.
"""
function save_chevalley_polytope(D::ChevalleyData, dir::AbstractString;
  precompute::Bool=true)

  P = chevalley_polytope(D)
  d, deg = degree_of_embedding(D.R, D.varpi)
  vol = normalised_volume_of(P)
  idp = has_idp(P)
  if precompute
    vertices(P)
    facets(P)
    lattice_points(P)
  end
  t = _type_and_rank(D.R)
  atts = Dict{String,String}(
    "CHEVALLEY_ROOT_SYSTEM" => string(t[1], t[2]),
    "CHEVALLEY_VARPI" => join(D.varpi, " "),
    "CHEVALLEY_WORD" => join(D.r, " "),
    "CHEVALLEY_DIM_X" => string(d),
    "CHEVALLEY_DEGREE_X" => string(deg),
    "CHEVALLEY_NORMALISED_VOLUME" => string(vol),
    "CHEVALLEY_IS_NOBODY" => string(vol == deg),
    "CHEVALLEY_HAS_IDP" => string(idp),
    "CHEVALLEY_SOURCE" =>
      "Chevalley polytope, arXiv:2411.10276; computed by chevalley_polytopes.jl",
  )
  name = polytope_name(D)
  return save_polymake(P, joinpath(dir, name * ".poly"); name=name, attachments=atts)
end

