###############################################################################
#
#   Conventions
#
#   The paper writes the reduced expression as
#
#       s = s_{r_l} s_{r_{l-1}} ... s_{r_1},
#
#   i.e. the RIGHTMOST letter is the first one, and the associated torus is
#
#       u_-(a) = y_{r_l}(a_l) ... y_{r_2}(a_2) y_{r_1}(a_1),
#
#   so that y_{r_1}(a_1) is the factor which hits the highest weight vector
#   first.  Throughout, a "paper word" is the vector
#
#       r = [r_1, r_2, ..., r_l],
#
#   which is the REVERSE of what `Oscar.word` returns (Oscar's convention is
#   `W(w)` = s_{w[1]} s_{w[2]} ... s_{w[k]}).  Valuation vectors are always
#   reported in the order (e_1, ..., e_l) with e_k the exponent of a_k, so
#   coordinate k belongs to position k of the paper word.
#
#   The term order is degrevlex with a_l > a_{l-1} > ... > a_1, and the
#   valuation takes the MINIMAL term (Definition "def:main_objects").
#
###############################################################################

"""
    parabolic_indices(varpi::Vector{Int}) -> Vector{Int}

The simple reflections generating `W_P`, where `P` is the parabolic
stabilising the highest weight line of `V_varpi`.  These are the indices `i`
with `<varpi, alpha_i^vee> = 0`, i.e. the zero entries of `varpi` written in
fundamental weight coordinates.
"""
parabolic_indices(varpi::Vector{Int}) = [i for i in 1:length(varpi) if varpi[i] == 0]

"""
    minimal_coset_representative(W::WeylGroup, S::Vector{Int}) -> WeylGroupElem

The minimal length representative `w^P` of the coset `w_0 W_S`, where `W_S` is
the standard parabolic subgroup generated by `s_i`, `i in S`.

Computed by greedy length descent: `w` is the minimal representative of
`w W_S` exactly when no `w s_i` with `i in S` is shorter.
"""
function minimal_coset_representative(W::WeylGroup, S::Vector{Int})
  w = longest_element(W)
  improved = true
  while improved
    improved = false
    for i in S
      v = w * gen(W, i)
      if length(v) < length(w)
        w = v
        improved = true
      end
    end
  end
  return w
end

"""
    paper_word(x::WeylGroupElem) -> Vector{Int}

The reduced word of `x` in the convention of the paper, i.e. reversed with
respect to `Oscar.word`, so that `x = s_{r[end]} * ... * s_{r[1]}`.
"""
paper_word(x::WeylGroupElem) = reverse(Int.(Oscar.word(x)))

"""
    all_paper_words(x::WeylGroupElem; up_to_commutation::Bool=false)

All reduced expressions for `x` in the paper's convention.  Outside the
minuscule case the Chevalley polytope genuinely depends on this choice, so
this is the object one wants to loop over.
"""
function all_paper_words(x::WeylGroupElem; up_to_commutation::Bool=false)
  return [reverse(Int.(w)) for w in reduced_expressions(x; up_to_commutation=up_to_commutation)]
end

"""
    heap_relations(R::RootSystem, r::Vector{Int}) -> Matrix{Bool}

The heap `H_s` of the paper word `r`, as its strict order relation:
`M[k, k'] == true` iff position `k` is strictly below position `k'`.

Positions `k < k'` are related whenever the letters do not commute (equal
indices, or adjacent in the Dynkin diagram); the heap is the transitive
closure of those.
"""
function heap_relations(R::RootSystem, r::Vector{Int})
  l = length(r)
  C = cartan_matrix(R)
  M = fill(false, l, l)
  for k in 1:l, kk in (k + 1):l
    if r[k] == r[kk] || !is_zero(C[r[k], r[kk]])
      M[k, kk] = true
    end
  end
  # transitive closure
  for m in 1:l, k in 1:l, kk in 1:l
    if M[k, m] && M[m, kk]
      M[k, kk] = true
    end
  end
  return M
end

"""
    degree_of_embedding(R::RootSystem, varpi::Vector{Int}) -> (Int, ZZRingElem)

The Borel-Hirzebruch degree formula quoted at the start of Appendix A,

    deg(X, V_varpi) = dim(X)! * prod_alpha <alpha^vee, varpi> / <alpha^vee, rho>,

the product being over the positive roots with `<alpha^vee, varpi> != 0`.
Returns `(dim X, deg X)`; `dim X` is the number of factors, which must agree
with `length(w^P)`.
"""
function degree_of_embedding(R::RootSystem, varpi::Vector{Int})
  n = rank(R)
  @req length(varpi) == n "varpi has the wrong number of coordinates"
  d = 0
  q = QQ(1)
  for cor in positive_coroots(R)
    m = Int.(collect(coefficients(cor)))
    pv = sum(m[i] * varpi[i] for i in 1:n)          # <alpha^vee, varpi>
    pr = sum(m[i] for i in 1:n)                     # <alpha^vee, rho> = height
    if !iszero(pv)
      d += 1
      q *= QQ(pv, pr)
    end
  end
  deg = factorial(ZZ(d)) * q
  @req is_one(denominator(deg)) "Borel-Hirzebruch degree is not an integer"
  return d, numerator(deg)
end

